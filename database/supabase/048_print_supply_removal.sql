-- A size remains shared by printing requests; each brand keeps its own inventory.
CREATE TABLE paper_brand_stocks (
  paper_brand_stock_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  paper_stock_id INTEGER NOT NULL REFERENCES bond_paper_stocks(paper_stock_id) ON DELETE RESTRICT,
  brand VARCHAR(100) NOT NULL,
  unopened_reams INTEGER NOT NULL DEFAULT 0 CHECK(unopened_reams>=0),
  average_expense_cost NUMERIC(10,2) NOT NULL DEFAULT 0 CHECK(average_expense_cost>=0),
  deleted_at TIMESTAMPTZ,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE UNIQUE INDEX paper_brand_size_idx ON paper_brand_stocks(paper_stock_id,lower(trim(brand)));
INSERT INTO paper_brand_stocks(paper_stock_id,brand,unopened_reams,average_expense_cost)
  SELECT p.paper_stock_id,COALESCE(NULLIF(trim(d.brand),''),'Unspecified brand'),p.unopened_reams,p.average_expense_cost
  FROM bond_paper_stocks p LEFT JOIN print_supply_details d ON d.paper_stock_id=p.paper_stock_id;
ALTER TABLE paper_stock_movements ADD COLUMN paper_brand_stock_id INTEGER REFERENCES paper_brand_stocks(paper_brand_stock_id) ON DELETE RESTRICT;
ALTER TABLE paper_brand_stocks ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON paper_brand_stocks FROM PUBLIC,anon,authenticated;
REVOKE ALL ON SEQUENCE paper_brand_stocks_paper_brand_stock_id_seq FROM PUBLIC,anon,authenticated;

-- Both quantities must commit together, including writes from older app sessions.
CREATE FUNCTION check_paper_brand_total() RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE target_id INTEGER; total INTEGER; expected INTEGER;
BEGIN
  IF TG_OP='DELETE' THEN target_id:=OLD.paper_stock_id; ELSE target_id:=NEW.paper_stock_id; END IF;
  SELECT unopened_reams INTO expected FROM bond_paper_stocks WHERE paper_stock_id=target_id;
  SELECT COALESCE(SUM(unopened_reams),0) INTO total FROM paper_brand_stocks WHERE paper_stock_id=target_id AND deleted_at IS NULL;
  IF expected IS NOT NULL AND expected<>total THEN
    RAISE EXCEPTION 'Paper brand stock and size total must be updated together' USING ERRCODE='23514';
  END IF;
  RETURN NULL;
END;
$$;
REVOKE ALL ON FUNCTION check_paper_brand_total() FROM PUBLIC,anon,authenticated;
CREATE CONSTRAINT TRIGGER paper_size_total_guard AFTER INSERT OR UPDATE ON bond_paper_stocks
  DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION check_paper_brand_total();
CREATE CONSTRAINT TRIGGER paper_brand_total_guard AFTER INSERT OR UPDATE OR DELETE ON paper_brand_stocks
  DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION check_paper_brand_total();
