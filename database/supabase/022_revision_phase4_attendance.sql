CREATE TABLE attendance_operation_settings (
 settings_id SMALLINT PRIMARY KEY CHECK(settings_id=1),
 service_purposes JSONB NOT NULL DEFAULT '["Printing"]'::jsonb CHECK(jsonb_typeof(service_purposes)='array'),
 preclosing_minutes SMALLINT CHECK(preclosing_minutes BETWEEN 1 AND 60),
 configured BOOLEAN NOT NULL DEFAULT FALSE,
 row_version INTEGER NOT NULL DEFAULT 1,
 updated_by BIGINT REFERENCES accounts(account_id), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
INSERT INTO attendance_operation_settings(settings_id,preclosing_minutes,configured) VALUES(1,5,TRUE);
CREATE TABLE library_operational_events (
 event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 title VARCHAR(150) NOT NULL,
 event_kind TEXT NOT NULL CHECK(event_kind IN ('Class','Meeting','Seminar')),
 space_name VARCHAR(150) NOT NULL,
 starts_at TIMESTAMPTZ NOT NULL, ends_at TIMESTAMPTZ NOT NULL CHECK(ends_at>starts_at),
 seat_capacity INTEGER NOT NULL CHECK(seat_capacity BETWEEN 0 AND 5000),
 allow_walk_ins BOOLEAN NOT NULL, allow_borrowing BOOLEAN NOT NULL, allow_printing BOOLEAN NOT NULL,
 lifecycle_status TEXT NOT NULL DEFAULT 'Active' CHECK(lifecycle_status IN ('Active','Cancelled')),
 row_version INTEGER NOT NULL DEFAULT 1,
 created_by BIGINT NOT NULL REFERENCES accounts(account_id), updated_by BIGINT REFERENCES accounts(account_id),
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX library_operational_events_window ON library_operational_events(lifecycle_status,starts_at,ends_at);
CREATE INDEX library_operational_events_creator ON library_operational_events(created_by);
CREATE INDEX library_operational_events_updater ON library_operational_events(updated_by);
ALTER TABLE attendance_logs ADD COLUMN seat_visit BOOLEAN;
ALTER TABLE attendance_logs ADD COLUMN checkout_source TEXT CHECK(checkout_source IN ('Scan','Automatic closing'));
CREATE INDEX attendance_logs_intervals ON attendance_logs(checked_in_at,checked_out_at);
CREATE TABLE attendance_scan_receipts (
 request_id VARCHAR(64) PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(user_id),
 actor_account_id BIGINT NOT NULL REFERENCES accounts(account_id),
 credential_id BIGINT NOT NULL REFERENCES attendance_qr_credentials(credential_id),
 payload_digest CHAR(64) NOT NULL,
 log_id BIGINT NOT NULL REFERENCES attendance_logs(log_id),
 action TEXT NOT NULL CHECK(action IN ('Entry','Exit')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX attendance_scan_receipts_user ON attendance_scan_receipts(user_id,created_at);
CREATE INDEX attendance_scan_receipts_actor ON attendance_scan_receipts(actor_account_id);
CREATE INDEX attendance_scan_receipts_credential ON attendance_scan_receipts(credential_id);
CREATE INDEX attendance_scan_receipts_log ON attendance_scan_receipts(log_id);
