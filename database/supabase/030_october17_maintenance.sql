CREATE VIEW october17_print_services WITH (security_invoker=true) AS
 SELECT CONCAT('P-',p.request_id) id,'Online request'::text source,u.full_name name,u.school_id,u.user_role role,
 p.file_name,p.page_count,p.number_of_copies,p.total_sheets,p.print_type::text,p.paper_size::text,p.calculated_cost,
 p.payment_status::text,p.job_status::text status,p.created_at AT TIME ZONE 'UTC' AT TIME ZONE 'Asia/Manila' service_time
 FROM print_requests p JOIN users u ON u.user_id=p.user_id
 UNION ALL SELECT CONCAT('H-',h.entry_id),'Historical entry',h.customer_name,u.school_id,u.user_role,
 h.description,h.pages,h.copies,h.pages*h.copies,h.print_type,h.paper_size,h.billed,
 CASE WHEN h.payment_state='Confirmed' AND h.amount_paid=h.billed THEN 'Paid' WHEN h.payment_state='Confirmed' THEN 'Partially Paid' ELSE h.payment_state END,
 'Historical entry',h.served_at AT TIME ZONE 'Asia/Manila' FROM historical_print_entries h LEFT JOIN users u ON u.user_id=h.user_id WHERE h.state='Active';
CREATE VIEW october17_print_revenue WITH (security_invoker=true) AS
 SELECT CONCAT('P-',c.print_cash_payment_id) id,CONCAT('P-',p.request_id) request_id,'Online request'::text source,u.full_name name,u.school_id,u.user_role role,
 p.file_name,p.print_type::text,p.paper_size::text,p.page_count,p.number_of_copies,p.total_sheets,c.amount_paid,c.received_at received,staff.full_name received_by
 FROM print_cash_payments c JOIN print_requests p ON p.request_id=c.request_id JOIN users u ON u.user_id=p.user_id LEFT JOIN users staff ON staff.user_id=c.received_by_user_id
 UNION ALL SELECT CONCAT('H-',h.entry_id),CONCAT('H-',h.entry_id),'Historical entry',h.customer_name,u.school_id,u.user_role,
 h.description,h.print_type,h.paper_size,h.pages,h.copies,h.pages*h.copies,h.amount_paid,h.received_at AT TIME ZONE 'Asia/Manila',NULL::text
 FROM historical_print_entries h LEFT JOIN users u ON u.user_id=h.user_id
 WHERE h.state='Active' AND h.payment_state='Confirmed';
CREATE VIEW october17_supply_expenses WITH (security_invoker=true) AS
 SELECT CONCAT('I-',m.ink_stock_movement_id) id,'Ink'::text supply_type,CONCAT(i.cartridge_type,' ',i.color_variation) supply,m.quantity_bottles::numeric quantity,'bottles'::text unit,
 m.unit_cost_per_bottle unit_cost,m.expense_amount expense,m.balance_before,m.balance_after,m.created_at AT TIME ZONE 'UTC' AT TIME ZONE 'Asia/Manila' recorded,u.full_name recorded_by
 FROM ink_stock_movements m JOIN ink_repository i ON i.ink_id=m.ink_id LEFT JOIN users u ON u.user_id=m.recorded_by_user_id WHERE m.movement_type='Restock'
 UNION ALL SELECT CONCAT('P-',m.paper_stock_movement_id),'Paper',p.paper_size_dimension,m.quantity_reams,'reams',m.unit_cost_per_ream,m.expense_amount,m.balance_before,m.balance_after,m.created_at AT TIME ZONE 'UTC' AT TIME ZONE 'Asia/Manila',u.full_name
 FROM paper_stock_movements m JOIN bond_paper_stocks p ON p.paper_stock_id=m.paper_stock_id LEFT JOIN users u ON u.user_id=m.recorded_by_user_id WHERE m.movement_type='Restock'
 UNION ALL SELECT CONCAT('O-',m.movement_id),'Other materials',m.item_name,m.quantity,m.unit,m.unit_cost,m.expense,m.balance_before,m.balance_after,m.created_at AT TIME ZONE 'Asia/Manila',u.full_name
 FROM maintained_stock_movements m JOIN maintained_stock_items i ON i.item_id=m.item_id JOIN accounts a ON a.account_id=m.actor_id LEFT JOIN users u ON u.user_id=a.user_id WHERE i.kind='printing' AND m.action='Restock';
CREATE VIEW october17_supply_snapshot WITH (security_invoker=true) AS
 SELECT 'Ink bottle'::text supply_type,CONCAT(i.cartridge_type,' ',i.color_variation) name,
 CONCAT_WS(' · ',d.brand,d.type_model,d.compatible_printer) specifications,'bottles'::text unit,i.available_bottles::numeric available,i.low_stock_threshold_bottles::numeric threshold,
 CASE WHEN i.available_bottles<=i.low_stock_threshold_bottles THEN 'Low stock' ELSE 'In stock' END status
 FROM ink_repository i LEFT JOIN print_supply_details d ON d.ink_id=i.ink_id
 UNION ALL SELECT 'Bond paper',p.paper_size_dimension,CONCAT_WS(' · ',d.paper_type,d.size_name,CASE WHEN d.width IS NOT NULL THEN CONCAT(d.width,' × ',d.height,' ',d.dimension_unit) END),'reams',p.unopened_reams,p.low_stock_threshold_reams,
 CASE WHEN p.unopened_reams<=p.low_stock_threshold_reams THEN 'Low stock' ELSE 'In stock' END FROM bond_paper_stocks p LEFT JOIN print_supply_details d ON d.paper_stock_id=p.paper_stock_id
 UNION ALL SELECT 'Other materials',i.name,i.specifications,i.unit,i.balance,i.threshold,CASE WHEN i.balance<=i.threshold THEN 'Low stock' ELSE 'In stock' END FROM maintained_stock_items i WHERE i.kind='printing' AND i.state='Active';
REVOKE ALL ON october17_print_services,october17_print_revenue,october17_supply_expenses,october17_supply_snapshot FROM anon,authenticated;
