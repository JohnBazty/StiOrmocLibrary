CREATE TABLE historical_print_entries (
  entry_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  served_at timestamptz NOT NULL, customer_name varchar(150) NOT NULL,
  user_id integer REFERENCES users(user_id), reference varchar(150), description varchar(500) NOT NULL,
  pages integer CHECK (pages > 0), copies integer CHECK (copies > 0), print_type varchar(60), paper_size varchar(60),
  billed numeric(12,2) NOT NULL CHECK (billed >= 0),
  payment_state text NOT NULL CHECK (payment_state IN ('Unpaid','Unverified','Confirmed')),
  amount_paid numeric(12,2) NOT NULL DEFAULT 0 CHECK (amount_paid >= 0 AND amount_paid <= billed),
  received_at timestamptz, payment_method varchar(40), payment_evidence varchar(500),
  state text NOT NULL DEFAULT 'Active' CHECK (state IN ('Active','Voided')),
  version integer NOT NULL DEFAULT 1, created_by bigint NOT NULL REFERENCES accounts(account_id),
  updated_by bigint NOT NULL REFERENCES accounts(account_id), created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (payment_state <> 'Confirmed' OR (amount_paid > 0 AND received_at IS NOT NULL AND payment_evidence IS NOT NULL AND length(payment_evidence) >= 3 AND payment_method IS NOT NULL)),
  CHECK (payment_state <> 'Unpaid' OR (amount_paid = 0 AND received_at IS NULL))
);
CREATE INDEX historical_print_service_idx ON historical_print_entries(served_at DESC,entry_id DESC);
CREATE INDEX historical_print_received_idx ON historical_print_entries(received_at) WHERE state='Active' AND payment_state='Confirmed';

CREATE TABLE print_supply_details (
  detail_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ink_id integer UNIQUE REFERENCES ink_repository(ink_id), paper_stock_id integer UNIQUE REFERENCES bond_paper_stocks(paper_stock_id),
  brand varchar(100), type_model varchar(100), compatible_printer varchar(150),
  paper_type varchar(100), size_name varchar(100), width numeric(9,3), height numeric(9,3), dimension_unit text CHECK (dimension_unit IN ('mm','cm','in')),
  version integer NOT NULL DEFAULT 1, updated_by bigint NOT NULL REFERENCES accounts(account_id), updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK ((ink_id IS NOT NULL)::integer + (paper_stock_id IS NOT NULL)::integer = 1),
  CHECK ((width IS NULL AND height IS NULL AND dimension_unit IS NULL) OR (width IS NOT NULL AND height IS NOT NULL AND width>0 AND height>0 AND dimension_unit IS NOT NULL))
);
CREATE TABLE maintained_item_categories (
  category_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind text NOT NULL CHECK (kind IN ('merchandise','printing')), name varchar(100) NOT NULL,
  state text NOT NULL DEFAULT 'Active' CHECK (state IN ('Active','Archived')),
  version integer NOT NULL DEFAULT 1, updated_by bigint NOT NULL REFERENCES accounts(account_id), updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(category_id,kind)
);
CREATE UNIQUE INDEX maintained_category_name_idx ON maintained_item_categories(kind,lower(name));
CREATE TABLE maintained_stock_items (
  item_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind text NOT NULL CHECK (kind IN ('merchandise','printing')), category_id bigint NOT NULL,
  name varchar(150) NOT NULL, specifications varchar(500) NOT NULL DEFAULT '',
  unit text NOT NULL CHECK (unit IN ('pieces','packs','boxes','rolls','metres')),
  price numeric(12,2) NOT NULL DEFAULT 0 CHECK (price>=0), balance numeric(12,3) NOT NULL DEFAULT 0 CHECK (balance>=0),
  threshold numeric(12,3) NOT NULL DEFAULT 0 CHECK (threshold>=0),
  state text NOT NULL DEFAULT 'Active' CHECK (state IN ('Active','Archived')),
  version integer NOT NULL DEFAULT 1, updated_by bigint NOT NULL REFERENCES accounts(account_id), updated_at timestamptz NOT NULL DEFAULT now(),
  FOREIGN KEY(category_id,kind) REFERENCES maintained_item_categories(category_id,kind),
  CHECK (unit='metres' OR (balance=trunc(balance) AND threshold=trunc(threshold)))
);
CREATE INDEX maintained_item_kind_idx ON maintained_stock_items(kind,state,item_id);
CREATE TABLE maintained_stock_movements (
  movement_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, item_id bigint NOT NULL REFERENCES maintained_stock_items(item_id),
  action text NOT NULL CHECK (action IN ('Opening','Restock','Use','Correction')),
  quantity numeric(12,3) NOT NULL, balance_before numeric(12,3) NOT NULL CHECK (balance_before>=0), balance_after numeric(12,3) NOT NULL CHECK (balance_after>=0),
  unit_cost numeric(12,2) NOT NULL DEFAULT 0 CHECK (unit_cost>=0), expense numeric(12,2) NOT NULL DEFAULT 0 CHECK (expense>=0),
  item_name varchar(150) NOT NULL, unit text NOT NULL, reason varchar(500) NOT NULL,
  actor_id bigint NOT NULL REFERENCES accounts(account_id), created_at timestamptz NOT NULL DEFAULT now(),
  CHECK (balance_after=balance_before+quantity)
);
CREATE INDEX maintained_stock_history_idx ON maintained_stock_movements(item_id,movement_id DESC);
CREATE TABLE library_maintenance_commands (
  actor_id bigint NOT NULL REFERENCES accounts(account_id), command_key uuid NOT NULL,
  input_hash char(64) NOT NULL, result jsonb NOT NULL, created_at timestamptz NOT NULL DEFAULT now(), PRIMARY KEY(actor_id,command_key)
);
CREATE TABLE library_maintenance_events (
  event_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  scope text NOT NULL, record_id bigint NOT NULL, actor_id bigint NOT NULL REFERENCES accounts(account_id),
  reason varchar(500) NOT NULL, before_data jsonb, after_data jsonb NOT NULL, created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX library_maintenance_history_idx ON library_maintenance_events(scope,record_id,event_id DESC);
