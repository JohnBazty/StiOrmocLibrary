-- Extend existing paper stock/pricing; preserve all quantities, prices and print history.
ALTER TABLE bond_paper_stocks
  ADD COLUMN is_active BOOLEAN NOT NULL DEFAULT TRUE,
  ADD COLUMN sheets_per_ream INTEGER NOT NULL DEFAULT 500 CHECK (sheets_per_ream BETWEEN 1 AND 10000),
  ADD COLUMN configuration_version INTEGER NOT NULL DEFAULT 1;
CREATE UNIQUE INDEX paper_size_normalized_name_idx ON bond_paper_stocks(LOWER(BTRIM(paper_size_dimension)));
ALTER TABLE paper_stock_movements ADD COLUMN client_request_id UUID;
CREATE UNIQUE INDEX paper_stock_request_idx ON paper_stock_movements(client_request_id) WHERE client_request_id IS NOT NULL;
CREATE TABLE paper_size_changes (
  change_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  paper_stock_id INTEGER NOT NULL REFERENCES bond_paper_stocks(paper_stock_id) ON DELETE RESTRICT,
  changed_by_account_id BIGINT NOT NULL REFERENCES accounts(account_id) ON DELETE RESTRICT,
  before_values JSONB,
  after_values JSONB NOT NULL,
  changed_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX paper_size_changes_item_idx ON paper_size_changes(paper_stock_id,change_id DESC);
ALTER TABLE paper_size_changes ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON paper_size_changes FROM PUBLIC,anon,authenticated;
REVOKE ALL ON SEQUENCE paper_size_changes_change_id_seq FROM PUBLIC,anon,authenticated;
