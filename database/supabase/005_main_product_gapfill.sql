-- 037 category shelf authority (data sync; MySQL <=> becomes IS DISTINCT FROM)
UPDATE physical_copies pc
SET shelf_location = c.shelf_location,
    updated_at = NOW()
FROM titles t
JOIN categories c ON c.category_id = t.category_id
JOIN floor_plan_shelves s ON s.label = c.shelf_location
WHERE t.title_id = pc.title_id
  AND t.record_type = 'Book'
  AND t.lifecycle_status = 'Active'
  AND pc.lifecycle_status = 'Active'
  AND pc.shelf_location IS DISTINCT FROM c.shelf_location;

UPDATE materials m
SET shelf_location = c.shelf_location,
    updated_at = NOW()
FROM categories c
JOIN floor_plan_shelves s ON s.label = c.shelf_location
WHERE c.category_id = m.category_id
  AND m.shelf_location IS DISTINCT FROM c.shelf_location;

UPDATE research_inventory ri
SET shelf_location = c.shelf_location,
    updated_at = NOW(),
    row_version = ri.row_version + 1
FROM titles t
JOIN categories c ON c.category_id = t.category_id
JOIN floor_plan_shelves s ON s.label = c.shelf_location
WHERE t.title_id = ri.title_id
  AND t.record_type = 'Research/Thesis'
  AND t.lifecycle_status = 'Active'
  AND ri.lifecycle_status = 'Active'
  AND ri.shelf_location IS DISTINCT FROM c.shelf_location;

