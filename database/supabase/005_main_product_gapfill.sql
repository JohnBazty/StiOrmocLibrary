CREATE TABLE IF NOT EXISTS print_payment_receipts (
  print_receipt_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  print_cash_payment_id BIGINT NOT NULL,
  request_id BIGINT NOT NULL,
  user_id BIGINT NOT NULL,
  receipt_number VARCHAR(32) NOT NULL,
  verification_code VARCHAR(16) NOT NULL,
  receipt_status TEXT NOT NULL DEFAULT 'Issued',
  student_name_snapshot VARCHAR(150) NOT NULL,
  school_id_snapshot VARCHAR(30) NOT NULL,
  file_name_snapshot VARCHAR(255) NOT NULL,
  page_count_snapshot INTEGER NOT NULL,
  copies_snapshot INTEGER NOT NULL,
  total_sheets_snapshot INTEGER NOT NULL,
  print_type_snapshot TEXT NOT NULL,
  paper_size_snapshot TEXT NOT NULL,
  amount_received DECIMAL(10,2) NOT NULL,
  payment_method TEXT NOT NULL DEFAULT 'Cash',
  received_by_user_id BIGINT DEFAULT NULL,
  received_by_name_snapshot VARCHAR(150) NOT NULL,
  received_at TIMESTAMP NOT NULL,
  reversed_by_user_id BIGINT DEFAULT NULL,
  reversed_at TIMESTAMP DEFAULT NULL,
  reversal_reason VARCHAR(255) DEFAULT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (print_receipt_id),
  CONSTRAINT uq_print_receipt_payment UNIQUE (print_cash_payment_id),
  CONSTRAINT uq_print_receipt_request UNIQUE (request_id),
  CONSTRAINT uq_print_receipt_number UNIQUE (receipt_number),
  CONSTRAINT uq_print_receipt_verification UNIQUE (verification_code),
  CONSTRAINT fk_print_receipt_payment
    FOREIGN KEY (print_cash_payment_id) REFERENCES print_cash_payments (print_cash_payment_id)
    ON UPDATE CASCADE ON DELETE RESTRICT,
  CONSTRAINT fk_print_receipt_request
    FOREIGN KEY (request_id) REFERENCES print_requests (request_id)
    ON UPDATE CASCADE ON DELETE RESTRICT,
  CONSTRAINT fk_print_receipt_user
    FOREIGN KEY (user_id) REFERENCES users (user_id)
    ON UPDATE CASCADE ON DELETE RESTRICT,
  CONSTRAINT fk_print_receipt_receiver
    FOREIGN KEY (received_by_user_id) REFERENCES users (user_id)
    ON UPDATE CASCADE ON DELETE SET NULL,
  CONSTRAINT fk_print_receipt_reverser
    FOREIGN KEY (reversed_by_user_id) REFERENCES users (user_id)
    ON UPDATE CASCADE ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_print_receipt_user_date ON print_payment_receipts (user_id, received_at);
CREATE INDEX IF NOT EXISTS idx_print_receipt_status_date ON print_payment_receipts (receipt_status, received_at);

INSERT INTO print_payment_receipts (
  print_cash_payment_id, request_id, user_id, receipt_number, verification_code,
  student_name_snapshot, school_id_snapshot, file_name_snapshot, page_count_snapshot,
  copies_snapshot, total_sheets_snapshot, print_type_snapshot, paper_size_snapshot,
  amount_received, payment_method, received_by_user_id, received_by_name_snapshot, received_at
)
SELECT
  p.print_cash_payment_id,
  p.request_id,
  pr.user_id,
  'PR-' || to_char(p.received_at, 'YYYYMMDD') || '-' || lpad(p.print_cash_payment_id::text, 6, '0'),
  upper(substr(encode(digest('PRINT-' || p.print_cash_payment_id::text || '-' || pr.user_id::text || '-' || p.received_at::text, 'sha256'), 'hex'), 1, 16)),
  u.full_name,
  u.school_id,
  pr.file_name,
  pr.page_count,
  pr.number_of_copies,
  pr.total_sheets,
  pr.print_type,
  pr.paper_size,
  p.amount_paid,
  'Cash',
  p.received_by_user_id,
  COALESCE(staff.full_name, 'Authorized library personnel'),
  p.received_at
FROM print_cash_payments p
INNER JOIN print_requests pr ON pr.request_id = p.request_id
INNER JOIN users u ON u.user_id = pr.user_id
LEFT JOIN users staff ON staff.user_id = p.received_by_user_id
ON CONFLICT (print_cash_payment_id) DO NOTHING;
