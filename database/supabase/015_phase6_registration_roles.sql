CREATE TABLE IF NOT EXISTS profile_avatar_submissions (
  submission_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id BIGINT NOT NULL REFERENCES accounts(account_id),
  storage_path VARCHAR(255) NOT NULL UNIQUE,
  mime_type VARCHAR(30) NOT NULL,
  status VARCHAR(16) NOT NULL DEFAULT 'Pending' CHECK (status IN ('Pending','Approved','Rejected')),
  submitted_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  reviewed_by_account_id BIGINT REFERENCES accounts(account_id),
  reviewed_at TIMESTAMPTZ,
  review_reason VARCHAR(500)
);
CREATE INDEX IF NOT EXISTS idx_profile_avatars_account ON profile_avatar_submissions(account_id, submitted_at DESC);
CREATE INDEX IF NOT EXISTS idx_profile_avatars_pending ON profile_avatar_submissions(status, submitted_at) WHERE status='Pending';

