CREATE TABLE IF NOT EXISTS registration_requests (
  request_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  school_id VARCHAR(50) NOT NULL UNIQUE,
  email VARCHAR(191) NOT NULL UNIQUE,
  first_name VARCHAR(100) NOT NULL,
  last_name VARCHAR(100) NOT NULL,
  program_strand VARCHAR(150),
  year_grade_level VARCHAR(100),
  requested_role VARCHAR(20) NOT NULL CHECK (requested_role IN ('Student', 'Faculty', 'Librarian', 'Staff')),
  password_hash VARCHAR(255),
  status VARCHAR(24) NOT NULL DEFAULT 'PendingEmail' CHECK (status IN ('PendingEmail', 'PendingApproval', 'Rejected', 'Completed')),
  code_hash CHAR(64),
  code_expires_at TIMESTAMPTZ,
  code_sent_at TIMESTAMPTZ,
  code_attempts SMALLINT NOT NULL DEFAULT 0,
  email_verified_at TIMESTAMPTZ,
  reviewed_by_account_id BIGINT REFERENCES accounts(account_id),
  reviewed_at TIMESTAMPTZ,
  review_reason VARCHAR(500),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_registration_requests_status ON registration_requests(status, created_at);

