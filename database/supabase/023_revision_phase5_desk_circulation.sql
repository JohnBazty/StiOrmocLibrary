-- Additive: retain authoritative home loans, account/copy identities and history.
CREATE TABLE IF NOT EXISTS in_library_uses (
  use_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(user_id) ON DELETE RESTRICT,
  physical_copy_id BIGINT NOT NULL REFERENCES physical_copies(physical_copy_id) ON DELETE RESTRICT,
  material_id BIGINT NOT NULL REFERENCES materials(material_id) ON DELETE RESTRICT,
  attendance_log_id BIGINT NOT NULL REFERENCES attendance_logs(log_id) ON DELETE RESTRICT,
  started_at TIMESTAMPTZ NOT NULL,
  hand_back_by TIMESTAMPTZ NOT NULL,
  ended_at TIMESTAMPTZ,
  condition_out VARCHAR(40) NOT NULL,
  condition_in VARCHAR(40),
  assessment_note VARCHAR(500),
  status VARCHAR(20) NOT NULL DEFAULT 'Open' CHECK (status IN ('Open','Review','Returned')),
  started_by_account_id BIGINT NOT NULL REFERENCES accounts(account_id) ON DELETE RESTRICT,
  returned_by_account_id BIGINT REFERENCES accounts(account_id) ON DELETE RESTRICT,
  reviewed_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CHECK (hand_back_by >= started_at),
  CHECK ((status = 'Returned') = (ended_at IS NOT NULL))
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_in_library_open_copy ON in_library_uses(physical_copy_id) WHERE ended_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_in_library_user ON in_library_uses(user_id,started_at DESC);
CREATE INDEX IF NOT EXISTS idx_in_library_cutoff ON in_library_uses(hand_back_by) WHERE ended_at IS NULL;
CREATE TABLE IF NOT EXISTS circulation_scan_receipts (
  request_id VARCHAR(64) PRIMARY KEY,
  actor_account_id BIGINT NOT NULL REFERENCES accounts(account_id) ON DELETE RESTRICT,
  operation VARCHAR(20) NOT NULL CHECK (operation IN ('TakeHome','InLibrary','Return')),
  payload_digest CHAR(64) NOT NULL,
  result JSONB NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
ALTER TABLE in_library_uses ENABLE ROW LEVEL SECURITY;
ALTER TABLE circulation_scan_receipts ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON in_library_uses,circulation_scan_receipts FROM PUBLIC,anon,authenticated;
