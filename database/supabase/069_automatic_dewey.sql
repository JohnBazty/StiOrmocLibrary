-- Reviewed ISBN-based Dewey classification; no changes to existing assignments or call numbers.
CREATE TABLE IF NOT EXISTS public.dewey_classifications (
  classification_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code TEXT NOT NULL UNIQUE CHECK (length(code) <= 64 AND code ~ '^[0-9]{3}(\.[0-9]+)?$'),
  description TEXT CHECK (length(description) <= 255),
  lifecycle_status TEXT NOT NULL DEFAULT 'Active' CHECK (lifecycle_status IN ('Active','Archived')),
  row_version INTEGER NOT NULL DEFAULT 1 CHECK (row_version > 0),
  created_by BIGINT REFERENCES public.accounts(account_id) ON DELETE SET NULL,
  updated_by BIGINT REFERENCES public.accounts(account_id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
ALTER TABLE public.physical_copies ADD COLUMN IF NOT EXISTS dewey_classification_id BIGINT REFERENCES public.dewey_classifications(classification_id) ON DELETE RESTRICT;
ALTER TABLE public.physical_copies ADD COLUMN IF NOT EXISTS dewey_version INTEGER NOT NULL DEFAULT 0 CHECK (dewey_version >= 0);
CREATE INDEX IF NOT EXISTS ix_copy_dewey ON public.physical_copies(dewey_classification_id);
CREATE TABLE IF NOT EXISTS public.dewey_assignment_events (
  event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  physical_copy_id BIGINT REFERENCES public.physical_copies(physical_copy_id) ON DELETE SET NULL,
  accession_number TEXT NOT NULL,
  previous_code TEXT,
  new_code TEXT,
  source TEXT NOT NULL CHECK (source IN ('manual','open_library')),
  source_url TEXT,
  actor_account_id BIGINT NOT NULL REFERENCES public.accounts(account_id) ON DELETE RESTRICT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS ix_dewey_event_copy ON public.dewey_assignment_events(physical_copy_id, created_at);
CREATE INDEX IF NOT EXISTS ix_dewey_event_actor ON public.dewey_assignment_events(actor_account_id);
CREATE INDEX IF NOT EXISTS ix_dewey_created_by ON public.dewey_classifications(created_by);
CREATE INDEX IF NOT EXISTS ix_dewey_updated_by ON public.dewey_classifications(updated_by);
ALTER TABLE public.dewey_classifications ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.dewey_assignment_events ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.dewey_classifications, public.dewey_assignment_events FROM PUBLIC, anon, authenticated;
REVOKE ALL ON SEQUENCE public.dewey_classifications_classification_id_seq, public.dewey_assignment_events_event_id_seq FROM PUBLIC, anon, authenticated;
