CREATE TABLE IF NOT EXISTS login_attempt_windows (
  identifier_hash text PRIMARY KEY, failed_count integer NOT NULL DEFAULT 0,
  window_started_at timestamptz NOT NULL DEFAULT now(), locked_until timestamptz
);
CREATE TABLE IF NOT EXISTS login_otp_challenges (
  challenge_id uuid PRIMARY KEY, account_id bigint NOT NULL REFERENCES accounts(account_id),
  auth_version integer NOT NULL, code_hash text, failed_count integer NOT NULL DEFAULT 0,
  expires_at timestamptz NOT NULL, sent_at timestamptz NOT NULL DEFAULT now(),
  consumed_at timestamptz, resend_count integer NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS login_otp_account_idx ON login_otp_challenges(account_id, sent_at DESC);
CREATE TABLE IF NOT EXISTS library_login_sessions (
  session_id uuid PRIMARY KEY, account_id bigint NOT NULL REFERENCES accounts(account_id),
  auth_version integer NOT NULL, last_activity_at timestamptz NOT NULL DEFAULT now(),
  created_at timestamptz NOT NULL DEFAULT now(), revoked_at timestamptz
);
CREATE INDEX IF NOT EXISTS library_login_session_account_idx ON library_login_sessions(account_id);
CREATE TABLE IF NOT EXISTS clearance_semester_schedules (
  academic_term_id bigint PRIMARY KEY REFERENCES academic_terms(academic_term_id),
  deadline_at timestamptz, row_version integer NOT NULL DEFAULT 1,
  updated_by bigint NOT NULL REFERENCES accounts(account_id), updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS clearance_schedule_events (
  event_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  academic_term_id bigint NOT NULL REFERENCES academic_terms(academic_term_id),
  previous_deadline timestamptz, deadline_at timestamptz,
  actor_id bigint NOT NULL REFERENCES accounts(account_id), created_at timestamptz NOT NULL DEFAULT now()
);
