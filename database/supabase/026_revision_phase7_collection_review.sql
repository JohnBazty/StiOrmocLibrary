CREATE TABLE collection_reference_versions (
 reference_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 academic_year VARCHAR(30) NOT NULL,
 reference_year SMALLINT NOT NULL CHECK(reference_year BETWEEN 1000 AND 9998),
 review_age SMALLINT NOT NULL DEFAULT 5 CHECK(review_age=5),
 approved_by BIGINT REFERENCES accounts(account_id),
 approval_source VARCHAR(300) NOT NULL,
 approved_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
INSERT INTO collection_reference_versions(academic_year,reference_year,approval_source)
VALUES ('2026–2027',2026,'Owner confirmation: starting year, 2026-10-12');
CREATE TABLE collection_review_settings (
 settings_id SMALLINT PRIMARY KEY CHECK(settings_id=1),
 reference_id BIGINT NOT NULL REFERENCES collection_reference_versions(reference_id),
 row_version INTEGER NOT NULL DEFAULT 1
);
INSERT INTO collection_review_settings VALUES(1,1,1);
CREATE TABLE collection_age_status (
 title_id BIGINT PRIMARY KEY REFERENCES titles(title_id),
 reference_id BIGINT NOT NULL REFERENCES collection_reference_versions(reference_id),
 age_status VARCHAR(20) NOT NULL CHECK(age_status IN ('Updated','Outdated','Unknown','Future')),
 checked_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE collection_review_decisions (
 decision_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 title_id BIGINT NOT NULL REFERENCES titles(title_id),
 reference_id BIGINT NOT NULL REFERENCES collection_reference_versions(reference_id),
 decision VARCHAR(30) NOT NULL CHECK(decision IN ('Retain','Replace','Recommend archive','Verify metadata')),
 note VARCHAR(2000) NOT NULL,
 evidence JSONB NOT NULL,
 decided_by BIGINT NOT NULL REFERENCES accounts(account_id),
 decided_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX ix_collection_decision_title ON collection_review_decisions(title_id,decision_id DESC);
CREATE INDEX ix_collection_decision_actor ON collection_review_decisions(decided_by);
CREATE TABLE collection_requirement_versions (
 requirement_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 program_id BIGINT NOT NULL REFERENCES catalog_programs(program_id),
 course_id BIGINT REFERENCES catalog_courses(course_id),
 source_citation VARCHAR(500) NOT NULL,
 source_url VARCHAR(1000) NOT NULL,
 source_section VARCHAR(150) NOT NULL,
 effective_from DATE NOT NULL,
 effective_until DATE CHECK(effective_until IS NULL OR effective_until>=effective_from),
 counting_basis VARCHAR(20) NOT NULL CHECK(counting_basis IN ('Titles','Editions','Physical copies')),
 minimum_count INTEGER NOT NULL CHECK(minimum_count BETWEEN 0 AND 1000000),
 minimum_recent INTEGER NOT NULL CHECK(minimum_recent BETWEEN 0 AND 1000000),
 maximum_age SMALLINT NOT NULL CHECK(maximum_age BETWEEN 0 AND 1000),
 year_basis VARCHAR(20) NOT NULL CHECK(year_basis IN ('Publication','Copyright')),
 include_digital BOOLEAN NOT NULL DEFAULT FALSE,
 eligible_digital_ids JSONB NOT NULL DEFAULT '[]' CHECK(jsonb_typeof(eligible_digital_ids)='array'),
 approved BOOLEAN NOT NULL DEFAULT FALSE,
 mapping_verified BOOLEAN NOT NULL DEFAULT FALSE,
 is_active BOOLEAN NOT NULL DEFAULT TRUE,
 approval_note VARCHAR(2000) NOT NULL,
 created_by BIGINT NOT NULL REFERENCES accounts(account_id),
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX ix_collection_requirement_scope ON collection_requirement_versions(program_id,course_id,requirement_id DESC);
CREATE INDEX ix_collection_requirement_actor ON collection_requirement_versions(created_by);
CREATE TABLE collection_review_alerts (
 alert_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 dedupe_key VARCHAR(200) NOT NULL UNIQUE,
 title_id BIGINT REFERENCES titles(title_id),
 requirement_id BIGINT REFERENCES collection_requirement_versions(requirement_id),
 reference_id BIGINT NOT NULL REFERENCES collection_reference_versions(reference_id),
 message VARCHAR(1000) NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX ix_collection_alert_title ON collection_review_alerts(title_id);
CREATE INDEX ix_collection_alert_requirement ON collection_review_alerts(requirement_id);
CREATE TABLE collection_requirement_status (
 requirement_id BIGINT PRIMARY KEY REFERENCES collection_requirement_versions(requirement_id),
 status VARCHAR(30) NOT NULL,
 checked_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX ix_collection_reference_actor ON collection_reference_versions(approved_by);
CREATE INDEX ix_collection_age_reference ON collection_age_status(reference_id);
CREATE INDEX ix_collection_decision_reference ON collection_review_decisions(reference_id);
CREATE INDEX ix_collection_requirement_course ON collection_requirement_versions(course_id);
CREATE INDEX ix_collection_alert_reference ON collection_review_alerts(reference_id);
CREATE FUNCTION collection_preserve_history() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
 RAISE EXCEPTION 'Collection approvals and decisions are append-only; create a new version';
END $$;
REVOKE ALL ON FUNCTION collection_preserve_history() FROM PUBLIC,anon,authenticated;
CREATE TRIGGER preserve_collection_reference BEFORE UPDATE OR DELETE ON collection_reference_versions
FOR EACH ROW EXECUTE FUNCTION collection_preserve_history();
CREATE TRIGGER preserve_collection_requirement BEFORE UPDATE OR DELETE ON collection_requirement_versions
FOR EACH ROW EXECUTE FUNCTION collection_preserve_history();
CREATE TRIGGER preserve_collection_decision BEFORE UPDATE OR DELETE ON collection_review_decisions
FOR EACH ROW EXECUTE FUNCTION collection_preserve_history();
-- Resolve the current schema so the same reviewed DDL can be exercised in isolated tests.
DO $$ DECLARE t TEXT; seq TEXT; BEGIN
 FOREACH t IN ARRAY ARRAY['collection_reference_versions','collection_review_settings','collection_age_status','collection_review_decisions','collection_requirement_versions','collection_review_alerts','collection_requirement_status'] LOOP
  EXECUTE format('ALTER TABLE %I.%I ENABLE ROW LEVEL SECURITY',current_schema(),t);
  EXECUTE format('REVOKE ALL ON TABLE %I.%I FROM PUBLIC,anon,authenticated',current_schema(),t);
  SELECT pg_get_serial_sequence(format('%I.%I',current_schema(),t),a.attname) INTO seq
  FROM pg_attribute a WHERE a.attrelid=to_regclass(format('%I.%I',current_schema(),t)) AND a.attidentity<>'' LIMIT 1;
  IF seq IS NOT NULL THEN EXECUTE format('REVOKE ALL ON SEQUENCE %s FROM PUBLIC,anon,authenticated',seq); END IF;
 END LOOP;
END $$;
