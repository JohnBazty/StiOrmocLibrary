-- Reusable color/type choices are configuration, separate from purchased stock.
CREATE TABLE ink_color_types (
  ink_color_type_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cartridge_type VARCHAR(100) NOT NULL CHECK(length(trim(cartridge_type))>=2),
  color_variation VARCHAR(60) NOT NULL CHECK(length(trim(color_variation))>=1),
  created_by_account_id BIGINT REFERENCES accounts(account_id) ON DELETE RESTRICT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE UNIQUE INDEX ink_color_type_name_idx ON ink_color_types(lower(trim(cartridge_type)),lower(trim(color_variation)));
INSERT INTO ink_color_types(cartridge_type,color_variation)
  SELECT DISTINCT ON (lower(trim(cartridge_type)),lower(trim(color_variation))) trim(cartridge_type),trim(color_variation)
  FROM ink_repository WHERE length(trim(cartridge_type))>=2 AND length(trim(color_variation))>=1
  ORDER BY lower(trim(cartridge_type)),lower(trim(color_variation)),ink_id;
ALTER TABLE ink_color_types ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON ink_color_types FROM PUBLIC,anon,authenticated;
REVOKE ALL ON SEQUENCE ink_color_types_ink_color_type_id_seq FROM PUBLIC,anon,authenticated;
