ALTER TABLE academic_terms ALTER COLUMN ends_on DROP NOT NULL;
CREATE TABLE enrollment_settings (
  settings_id SMALLINT PRIMARY KEY CHECK(settings_id=1),
  current_term_id BIGINT REFERENCES academic_terms(academic_term_id),
  enforcement_enabled BOOLEAN NOT NULL DEFAULT FALSE,
  row_version INTEGER NOT NULL DEFAULT 1,
  updated_by BIGINT REFERENCES accounts(account_id),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
INSERT INTO enrollment_settings(settings_id) VALUES(1);
CREATE TABLE enrollment_import_batches (
  batch_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  academic_term_id BIGINT NOT NULL REFERENCES academic_terms(academic_term_id),
  filename VARCHAR(255) NOT NULL,
  file_sha256 CHAR(64) NOT NULL,
  config_sha256 CHAR(64) NOT NULL,
  source_date DATE NOT NULL,
  roster_scope VARCHAR(20) NOT NULL CHECK(roster_scope IN ('Complete','Partial')),
  listed_enrolled BOOLEAN NOT NULL,
  batch_status VARCHAR(20) NOT NULL DEFAULT 'Preview' CHECK(batch_status IN ('Preview','Confirmed')),
  student_count INTEGER NOT NULL CHECK(student_count>0),
  error_count INTEGER NOT NULL CHECK(error_count>=0),
  warning_count INTEGER NOT NULL CHECK(warning_count>=0),
  created_by BIGINT NOT NULL REFERENCES accounts(account_id),
  confirmed_by BIGINT REFERENCES accounts(account_id),
  confirmed_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE(academic_term_id,file_sha256),
  CHECK((batch_status='Confirmed')=(confirmed_at IS NOT NULL AND confirmed_by IS NOT NULL))
);
CREATE TABLE enrollment_import_rows (
  row_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  batch_id BIGINT NOT NULL REFERENCES enrollment_import_batches(batch_id),
  source_sheet VARCHAR(100) NOT NULL,
  source_row INTEGER NOT NULL,
  school_id VARCHAR(50) NOT NULL,
  student_name VARCHAR(200) NOT NULL,
  program VARCHAR(150) NOT NULL,
  year_level VARCHAR(50) NOT NULL,
  section VARCHAR(100) NOT NULL DEFAULT '',
  school_email VARCHAR(255) NOT NULL DEFAULT '',
  enrollment_status VARCHAR(20) NOT NULL CHECK(enrollment_status IN ('Enrolled','Not Enrolled','Unknown')),
  errors JSONB NOT NULL DEFAULT '[]',
  warnings JSONB NOT NULL DEFAULT '[]',
  UNIQUE(batch_id,source_sheet,source_row)
);
CREATE INDEX ix_enrollment_row_school ON enrollment_import_rows(school_id,batch_id);
CREATE INDEX ix_enrollment_batch_term ON enrollment_import_batches(academic_term_id,batch_status,batch_id);
CREATE TABLE enrollment_review_events (
  event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  account_id BIGINT REFERENCES accounts(account_id),
  academic_term_id BIGINT REFERENCES academic_terms(academic_term_id),
  batch_id BIGINT REFERENCES enrollment_import_batches(batch_id),
  actor_account_id BIGINT NOT NULL REFERENCES accounts(account_id),
  action VARCHAR(40) NOT NULL,
  before_data JSONB,
  after_data JSONB,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
