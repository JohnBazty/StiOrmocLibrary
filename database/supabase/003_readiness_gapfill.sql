CREATE TABLE IF NOT EXISTS print_status_history (
  print_status_history_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_id BIGINT NOT NULL REFERENCES print_requests (request_id) ON UPDATE CASCADE ON DELETE CASCADE,
  from_status VARCHAR(30) DEFAULT NULL,
  to_status VARCHAR(30) NOT NULL,
  changed_by_user_id BIGINT DEFAULT NULL REFERENCES users (user_id) ON UPDATE CASCADE ON DELETE SET NULL,
  reason VARCHAR(255) DEFAULT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

