CREATE TABLE IF NOT EXISTS barcode_sequences (
  sequence_year SMALLINT NOT NULL,
  last_value INTEGER NOT NULL DEFAULT 0,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (sequence_year)
);

CREATE TABLE IF NOT EXISTS inventory_audit_events (
  inventory_audit_event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  physical_copy_id BIGINT NOT NULL REFERENCES physical_copies (physical_copy_id) ON UPDATE CASCADE ON DELETE RESTRICT,
  barcode_snapshot VARCHAR(100) NOT NULL,
  event_type TEXT NOT NULL,
  previous_condition TEXT DEFAULT NULL,
  new_condition TEXT DEFAULT NULL,
  previous_availability TEXT DEFAULT NULL,
  new_availability TEXT DEFAULT NULL,
  verified_by_user_id BIGINT DEFAULT NULL REFERENCES users (user_id) ON UPDATE CASCADE ON DELETE SET NULL,
  verified_by_label VARCHAR(255) NOT NULL,
  action_reason VARCHAR(255) DEFAULT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_inventory_audit_copy_date ON inventory_audit_events (physical_copy_id, created_at);
CREATE INDEX IF NOT EXISTS idx_inventory_audit_barcode_date ON inventory_audit_events (barcode_snapshot, created_at);

CREATE TABLE IF NOT EXISTS print_pricing_rules (
  pricing_rule_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  print_type TEXT NOT NULL,
  paper_size TEXT NOT NULL,
  price_per_page DECIMAL(10,2) NOT NULL,
  is_active SMALLINT NOT NULL DEFAULT 1,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT NULL,
  CONSTRAINT uq_print_pricing_type_size UNIQUE (print_type, paper_size)
);

