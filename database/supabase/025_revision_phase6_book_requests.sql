-- Additive Phase 6: reservations remain the request ledger, loans remain authoritative.
-- The API uses the same settings-row lock as Phase 5 before allocating copies.
ALTER TABLE reservations ADD COLUMN client_request_id VARCHAR(100);
ALTER TABLE reservations ADD COLUMN preparation_started_at TIMESTAMPTZ;
ALTER TABLE reservations ADD COLUMN ready_at TIMESTAMPTZ;
CREATE UNIQUE INDEX uq_request_client_key ON reservations(user_id,client_request_id)
  WHERE client_request_id IS NOT NULL;
CREATE INDEX ix_request_waiting_title ON reservations(book_title_id,queue_position,reserved_at,reservation_id)
  WHERE reservation_status IN ('pending','approved') AND assigned_physical_copy_id IS NULL;

CREATE TABLE book_request_events (
  event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reservation_id BIGINT NOT NULL REFERENCES reservations(reservation_id) ON DELETE RESTRICT,
  event_status VARCHAR(32) NOT NULL CHECK (event_status IN ('received','waiting','preparing','ready_for_pickup','claimed','cancelled','expired')),
  physical_copy_id BIGINT REFERENCES physical_copies(physical_copy_id) ON DELETE RESTRICT,
  occurred_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  pickup_deadline TIMESTAMPTZ,
  UNIQUE(reservation_id,event_status)
);
CREATE TABLE book_request_email_deliveries (
  delivery_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  event_id BIGINT NOT NULL UNIQUE REFERENCES book_request_events(event_id) ON DELETE RESTRICT,
  recipient VARCHAR(191) NOT NULL,
  subject VARCHAR(255) NOT NULL,
  message_body TEXT NOT NULL,
  status VARCHAR(16) NOT NULL CHECK(status IN ('Pending','Sending','Sent','Failed','Disabled')),
  attempts INTEGER NOT NULL DEFAULT 0,
  next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  lease_until TIMESTAMPTZ,
  lease_token UUID,
  sent_at TIMESTAMPTZ,
  last_error VARCHAR(255)
);
CREATE INDEX ix_request_event_copy ON book_request_events(physical_copy_id) WHERE physical_copy_id IS NOT NULL;
CREATE INDEX ix_request_email_due ON book_request_email_deliveries(next_attempt_at,delivery_id)
  WHERE status IN ('Pending','Failed','Sending');
ALTER TABLE book_request_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE book_request_email_deliveries ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON book_request_events,book_request_email_deliveries FROM anon,authenticated;
REVOKE ALL ON SEQUENCE book_request_events_event_id_seq,book_request_email_deliveries_delivery_id_seq FROM anon,authenticated;

-- Preserve every existing cart transaction ID/group. Give unlinked Pending claims
-- a preparation request; never start a timer or send historical email on migration.
DO $$
DECLARE claim RECORD; request_id BIGINT; position INTEGER;
BEGIN
  FOR claim IN SELECT bt.*,pc.title_id FROM borrow_transactions bt
    JOIN physical_copies pc ON pc.physical_copy_id=bt.physical_copy_id
    WHERE bt.transaction_status='Pending' AND bt.reservation_id IS NULL
    ORDER BY bt.created_at,bt.transaction_id
  LOOP
    SELECT COALESCE(MAX(queue_position),0)+1 INTO position FROM reservations
      WHERE book_title_id=claim.title_id AND reservation_status IN ('pending','approved','ready_for_pickup');
    INSERT INTO reservations(user_id,material_id,book_title_id,accession_id,assigned_physical_copy_id,
      queue_position,reservation_status,reserved_at,borrowing_policy_version_id,preparation_started_at)
    VALUES(claim.user_id,claim.material_id,claim.title_id,claim.material_id,claim.physical_copy_id,
      position,'approved',claim.created_at,claim.borrowing_policy_version_id,NOW()) RETURNING reservation_id INTO request_id;
    UPDATE borrow_transactions SET reservation_id=request_id WHERE transaction_id=claim.transaction_id;
  END LOOP;
END $$;
UPDATE reservations SET ready_at=(pickup_deadline AT TIME ZONE 'Asia/Manila')-INTERVAL '24 hours'
  WHERE reservation_status='ready_for_pickup' AND pickup_deadline IS NOT NULL;
UPDATE reservations SET preparation_started_at=COALESCE(updated_at,reserved_at) AT TIME ZONE 'Asia/Manila'
  WHERE reservation_status='approved' AND assigned_physical_copy_id IS NOT NULL AND preparation_started_at IS NULL;
-- Initial historical event is evidence, not a fresh notification.
INSERT INTO book_request_events(reservation_id,event_status,physical_copy_id,occurred_at,pickup_deadline)
SELECT reservation_id,CASE reservation_status WHEN 'pending' THEN 'waiting' WHEN 'approved' THEN
  CASE WHEN assigned_physical_copy_id IS NULL THEN 'waiting' ELSE 'preparing' END ELSE reservation_status END,
  assigned_physical_copy_id,COALESCE(ready_at,preparation_started_at,reserved_at AT TIME ZONE 'Asia/Manila'),
  pickup_deadline AT TIME ZONE 'Asia/Manila' FROM reservations;
