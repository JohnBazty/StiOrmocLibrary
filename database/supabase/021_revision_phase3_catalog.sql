-- Additive catalog extensions. Existing title/copy/loan identities are retained.
CREATE TABLE catalog_resource_types (
  type_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL UNIQUE,
  record_kind TEXT NOT NULL CHECK (record_kind IN ('Book','Research/Thesis')),
  lifecycle_status TEXT NOT NULL DEFAULT 'Active' CHECK (lifecycle_status IN ('Active','Archived')),
  row_version INTEGER NOT NULL DEFAULT 1,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
INSERT INTO catalog_resource_types(name,record_kind) VALUES ('Book','Book'),('Research / Thesis','Research/Thesis');

CREATE TABLE catalog_locations (
  location_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(100) NOT NULL UNIQUE,
  lifecycle_status TEXT NOT NULL DEFAULT 'Active' CHECK (lifecycle_status IN ('Active','Archived')),
  row_version INTEGER NOT NULL DEFAULT 1,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
INSERT INTO catalog_locations(name)
SELECT DISTINCT shelf_location FROM (
  SELECT shelf_location FROM categories UNION SELECT shelf_location FROM physical_copies UNION SELECT shelf_location FROM research_inventory
) locations WHERE shelf_location IS NOT NULL AND TRIM(shelf_location) <> '' ON CONFLICT DO NOTHING;

CREATE TABLE catalog_programs (
  program_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(40) NOT NULL UNIQUE, name VARCHAR(150) NOT NULL,
  lifecycle_status TEXT NOT NULL DEFAULT 'Active' CHECK (lifecycle_status IN ('Active','Archived')),
  row_version INTEGER NOT NULL DEFAULT 1,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
INSERT INTO catalog_programs(code,name) VALUES
 ('GE','General Education'),('SHS','Senior High School'),
 ('BSIT','Bachelor of Science in Information Technology'),
 ('BSTM','Bachelor of Science in Tourism Management'),
 ('BSHM','Bachelor of Science in Hospitality Management');
CREATE TABLE catalog_courses (
  course_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  program_id BIGINT NOT NULL REFERENCES catalog_programs(program_id),
  code VARCHAR(40) NOT NULL, name VARCHAR(150) NOT NULL,
  lifecycle_status TEXT NOT NULL DEFAULT 'Active' CHECK (lifecycle_status IN ('Active','Archived')),
  row_version INTEGER NOT NULL DEFAULT 1,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE(program_id,code)
);
CREATE INDEX catalog_courses_program ON catalog_courses(program_id);
CREATE TABLE catalog_title_details (
  title_id BIGINT PRIMARY KEY REFERENCES titles(title_id) ON DELETE CASCADE,
  copyright_year SMALLINT CHECK (copyright_year BETWEEN 1000 AND 9999),
  edition VARCHAR(100), page_count INTEGER CHECK (page_count > 0),
  synopsis TEXT NOT NULL DEFAULT '', glossary_text TEXT NOT NULL DEFAULT '',
  type_id BIGINT REFERENCES catalog_resource_types(type_id),
  row_version INTEGER NOT NULL DEFAULT 1,
  updated_by BIGINT REFERENCES accounts(account_id),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX catalog_title_details_type ON catalog_title_details(type_id);
CREATE INDEX catalog_title_details_actor ON catalog_title_details(updated_by);
CREATE TABLE catalog_title_programs (
  title_id BIGINT NOT NULL REFERENCES titles(title_id) ON DELETE CASCADE,
  program_id BIGINT NOT NULL REFERENCES catalog_programs(program_id),
  PRIMARY KEY(title_id,program_id)
);
CREATE INDEX catalog_title_programs_program ON catalog_title_programs(program_id,title_id);
CREATE TABLE catalog_title_courses (
  title_id BIGINT NOT NULL REFERENCES titles(title_id) ON DELETE CASCADE,
  course_id BIGINT NOT NULL REFERENCES catalog_courses(course_id),
  PRIMARY KEY(title_id,course_id)
);
CREATE INDEX catalog_title_courses_course ON catalog_title_courses(course_id,title_id);

CREATE TABLE catalog_digital_files (
  file_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title_id BIGINT NOT NULL REFERENCES titles(title_id),
  storage_path TEXT NOT NULL UNIQUE, original_name VARCHAR(255) NOT NULL,
  byte_size INTEGER NOT NULL CHECK(byte_size > 0 AND byte_size <= 4194304),
  permission_note VARCHAR(1000) NOT NULL,
  lifecycle_status TEXT NOT NULL DEFAULT 'Active' CHECK(lifecycle_status IN ('Active','Archived')),
  uploaded_by BIGINT NOT NULL REFERENCES accounts(account_id),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX catalog_digital_files_title ON catalog_digital_files(title_id,lifecycle_status);
CREATE INDEX catalog_digital_files_actor ON catalog_digital_files(uploaded_by);

CREATE TABLE catalog_import_batches (
  batch_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fingerprint CHAR(64) NOT NULL UNIQUE, filename VARCHAR(255) NOT NULL,
  mapping_json JSONB NOT NULL,
  created_by BIGINT NOT NULL REFERENCES accounts(account_id),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX catalog_import_batches_actor ON catalog_import_batches(created_by);
CREATE TABLE catalog_import_rows (
  import_row_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  batch_id BIGINT NOT NULL REFERENCES catalog_import_batches(batch_id) ON DELETE CASCADE,
  sheet_name VARCHAR(100) NOT NULL, source_row INTEGER NOT NULL,
  source_json JSONB NOT NULL, data_json JSONB NOT NULL,
  status TEXT NOT NULL DEFAULT 'Review' CHECK(status IN ('Review','Ready','Imported','Skipped')),
  decision TEXT CHECK(decision IN ('new','add','link','reuse','skip')),
  target_title_id BIGINT REFERENCES titles(title_id),
  reuse_row_id BIGINT REFERENCES catalog_import_rows(import_row_id),
  reviewed_by BIGINT REFERENCES accounts(account_id), reviewed_at TIMESTAMPTZ,
  row_version INTEGER NOT NULL DEFAULT 1,
  result_json JSONB, error_text TEXT,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE(batch_id,sheet_name,source_row)
);
CREATE INDEX catalog_import_rows_work ON catalog_import_rows(batch_id,status,import_row_id);
CREATE INDEX catalog_import_rows_title ON catalog_import_rows(target_title_id);
CREATE INDEX catalog_import_rows_reuse ON catalog_import_rows(reuse_row_id);
CREATE INDEX catalog_import_rows_reviewer ON catalog_import_rows(reviewed_by);

DO $$
DECLARE table_name TEXT;
BEGIN
  FOREACH table_name IN ARRAY ARRAY['catalog_resource_types','catalog_locations','catalog_programs','catalog_courses',
    'catalog_title_details','catalog_title_programs','catalog_title_courses','catalog_digital_files',
    'catalog_import_batches','catalog_import_rows']
  LOOP
    EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY',table_name);
    EXECUTE format('REVOKE ALL ON TABLE public.%I FROM PUBLIC, anon, authenticated',table_name);
  END LOOP;
END $$;
