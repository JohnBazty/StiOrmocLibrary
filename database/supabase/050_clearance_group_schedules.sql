-- Multiple group periods; preserve existing deadlines and audit rows.
CREATE TABLE clearance_schedule_windows (
  schedule_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  academic_term_id bigint REFERENCES academic_terms(academic_term_id),
  enrollment_semester_id bigint REFERENCES enrollment_semesters(semester_id),
  audience text NOT NULL CHECK (audience IN ('All','BSIT','BSHM','BSTM','Grade 11','Grade 12')),
  starts_at timestamptz NOT NULL,
  ends_at timestamptz NOT NULL,
  row_version integer NOT NULL DEFAULT 1 CHECK (row_version > 0),
  request_key uuid UNIQUE,
  created_by bigint NOT NULL REFERENCES accounts(account_id),
  updated_by bigint NOT NULL REFERENCES accounts(account_id),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  cancelled_at timestamptz,
  CHECK (ends_at > starts_at),
  CHECK ((academic_term_id IS NOT NULL)::int + (enrollment_semester_id IS NOT NULL)::int = 1)
);
CREATE INDEX clearance_schedule_windows_term_idx ON clearance_schedule_windows(academic_term_id,audience,starts_at,ends_at) WHERE cancelled_at IS NULL;
CREATE INDEX clearance_schedule_windows_enrollment_idx ON clearance_schedule_windows(enrollment_semester_id,audience,starts_at,ends_at) WHERE cancelled_at IS NULL;
CREATE TABLE clearance_window_events (
  event_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  schedule_id bigint NOT NULL REFERENCES clearance_schedule_windows(schedule_id),
  action text NOT NULL CHECK (action IN ('Imported','Created','Updated','Cancelled')),
  actor_id bigint NOT NULL REFERENCES accounts(account_id),
  before_values jsonb,
  after_values jsonb NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
-- Retain previous all-student deadlines as periods beginning with their semester.
-- Unusual historical deadlines before the semester retain their original closing instant.
INSERT INTO clearance_schedule_windows(academic_term_id,audience,starts_at,ends_at,created_by,updated_by)
SELECT s.academic_term_id,'All',LEAST(t.starts_on::timestamp AT TIME ZONE 'Asia/Manila',s.deadline_at - interval '1 minute'),s.deadline_at,s.updated_by,s.updated_by
FROM clearance_semester_schedules s JOIN academic_terms t USING(academic_term_id) WHERE s.deadline_at IS NOT NULL;
INSERT INTO clearance_window_events(schedule_id,action,actor_id,after_values)
SELECT schedule_id,'Imported',created_by,to_jsonb(w) FROM clearance_schedule_windows w;
