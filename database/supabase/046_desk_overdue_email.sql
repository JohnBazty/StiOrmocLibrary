-- Explicit staff-triggered emails only. Do not backfill or send historical notices.
CREATE TABLE desk_overdue_email_deliveries (
  delivery_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  transaction_id BIGINT NOT NULL REFERENCES borrow_transactions(transaction_id) ON DELETE RESTRICT,
  renewal_count INTEGER NOT NULL CHECK (renewal_count >= 0),
  requested_by_account_id BIGINT NOT NULL REFERENCES accounts(account_id) ON DELETE RESTRICT,
  recipient VARCHAR(191) NOT NULL,
  status VARCHAR(16) NOT NULL DEFAULT 'Pending'
    CHECK (status IN ('Pending','Sending','Sent','Failed','Unconfirmed','Cancelled')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  lease_until TIMESTAMPTZ,
  lease_token UUID,
  sent_at TIMESTAMPTZ,
  last_error VARCHAR(255),
  UNIQUE (transaction_id,renewal_count)
);
CREATE INDEX ix_desk_email_pending ON desk_overdue_email_deliveries(delivery_id)
  WHERE status IN ('Pending','Sending');
ALTER TABLE desk_overdue_email_deliveries ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON desk_overdue_email_deliveries FROM PUBLIC,anon,authenticated;
REVOKE ALL ON SEQUENCE desk_overdue_email_deliveries_delivery_id_seq FROM PUBLIC,anon,authenticated;
