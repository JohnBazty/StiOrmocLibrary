const migration = (name: string) => readFileSync(new URL(`../../../../../database/supabase/${name}`, import.meta.url), 'utf8')

/** Real Postgres (PGlite) with the real conduct migrations applied to a minimal copy of the surrounding tables. Test use only. */
export async function createConductTestDb() {
  const pg = new PGlite()
  await pg.exec(`CREATE ROLE anon; CREATE ROLE authenticated;
 CREATE TABLE users(user_id BIGINT PRIMARY KEY,full_name TEXT,school_id TEXT,user_role TEXT,account_status TEXT);
 CREATE TABLE accounts(account_id BIGINT PRIMARY KEY,user_id BIGINT,school_id TEXT);
 CREATE TABLE admin_notifications(admin_notification_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,event_type TEXT NOT NULL,actor_user_id BIGINT,message_title VARCHAR(150) NOT NULL,message_body VARCHAR(500) NOT NULL);
 CREATE TABLE fines(fine_id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,transaction_id BIGINT,user_id BIGINT,fine_type TEXT,fine_amount NUMERIC,payment_status TEXT,calculation_basis TEXT,overdue_units INTEGER,rate_applied NUMERIC,applied_date TIMESTAMP,finalized_at TIMESTAMP,notes TEXT,updated_at TIMESTAMP);
 CREATE TABLE fine_infractions(fine_id BIGINT,category TEXT,incident_at TIMESTAMPTZ,incident_location TEXT,details TEXT,issued_by_user_id BIGINT);
 CREATE TABLE borrow_transactions(user_id BIGINT,transaction_status TEXT,lost_confirmed_at TIMESTAMP);
 CREATE TABLE lost_book_reports(user_id BIGINT,report_status TEXT,replacement_charge NUMERIC,payment_status TEXT);
 CREATE TABLE clearance_statuses(user_id BIGINT PRIMARY KEY,standing_status TEXT,reason_block_details TEXT,last_checked_at TIMESTAMP,updated_at TIMESTAMP);
 CREATE TABLE notifications(user_id BIGINT,message_title TEXT,message_body TEXT,trigger_type TEXT,source_type TEXT,source_id BIGINT,action_path TEXT,priority TEXT,dedupe_key TEXT,scheduled_for TIMESTAMP,delivered_at TIMESTAMP,UNIQUE(user_id,dedupe_key));
 INSERT INTO users VALUES(1,'Synthetic Librarian','LIB-TEST','Librarian','Active'),(2,'Synthetic Student','STU-TEST','Student','Active'),(3,'Synthetic Other','OTHER-TEST','Student','Active'),(4,'Synthetic Faculty','FAC-TEST','Faculty','Active');
 INSERT INTO accounts VALUES(1,1,'LIB-TEST'),(2,2,'STU-TEST'),(3,3,'OTHER-TEST'),(4,4,'FAC-TEST');`)
  await pg.exec(migration('056_conduct_records.sql'))
  await pg.exec(migration('074_violation_categories.sql'))
  const execute = async (sql: string, values: unknown[] = []) => {
    const write = /^\s*(INSERT|UPDATE|DELETE)/i.test(sql)
    let query = toPgPlaceholders(sql)
    if (/^\s*INSERT/i.test(sql) && !/RETURNING/i.test(sql)) query += ' RETURNING *'
    const result = await pg.query<Record<string, unknown>>(query, values)
    return write ? [{ insertId: Number(Object.values(result.rows[0] ?? {})[0] ?? 0), affectedRows: result.affectedRows, rows: result.rows }] : [result.rows]
  }
  const pool = { execute, getConnection: async () => ({ execute, beginTransaction: () => pg.exec('BEGIN'), commit: () => pg.exec('COMMIT'), rollback: () => pg.exec('ROLLBACK'), release() {} }) } as unknown as Pool
  return { pg, pool }
}

/** Back to the seeded state, so one database can serve every test in a file (each PGlite instance is heavy). */
export async function resetConductTestDb(pg: PGlite) {
  await pg.exec(`TRUNCATE conduct_events,conduct_incidents,conduct_students,fine_infractions,fines,notifications,clearance_statuses,admin_notifications RESTART IDENTITY CASCADE;
 DELETE FROM violation_categories WHERE name NOT IN ('Noise','Eating or food','Other conduct');
 UPDATE violation_categories SET warnings_before_fine=2,fine_amount=50,is_active=TRUE,description=NULL,updated_by_account_id=NULL;`)
}
