const setup:PrintSetup={version:1,imageFeeMono:100,imageFeeColor:300,scheduleEnabled:true,weekly:[{day:1,opens:'07:00',closes:'17:00'}],exceptions:[]}
test('Manila opening windows enforce exact boundaries, closed exceptions and next opening',()=>{
 assert.equal(printingWindow(setup,new Date('2026-11-15T23:00:00Z')).open,true)
 assert.equal(printingWindow(setup,new Date('2026-11-16T08:59:59Z')).open,true)
 const closed=printingWindow(setup,new Date('2026-11-16T09:00:00Z'))
 assert.equal(closed.open,false);assert.equal(closed.nextOpening,'2026-11-23T07:00:00+08:00')
 const holiday={...setup,exceptions:[{date:'2026-11-16',windows:[],reason:'School holiday'}]}
 assert.equal(printingWindow(holiday,new Date('2026-11-16T01:00:00Z')).reason,'School holiday')
 assert.equal(printingWindow({...holiday,scheduleEnabled:false}).open,true)
 assert.throws(()=>parseSetup({...setup,imageFeeMono:'1.001'}))
 assert.throws(()=>parseSetup({...setup,weekly:[{day:1,opens:'09:00',closes:'10:00'},{day:1,opens:'09:30',closes:'11:00'}]}))
 assert.throws(()=>parseSetup({...setup,exceptions:[{date:'2026-02-30',windows:[]}]}))
})
test('mixed-page totals count image additions once per eligible page per copy',()=>{
 const pages=[{page:1,hasImage:true,hasColor:false,imageReview:true},{page:2,hasImage:true,hasColor:true,imageReview:false},{page:3,hasImage:false,hasColor:true,imageReview:false}]
 const bill=pricePages(pages,3,'Automatic',200,500,setup)
 assert.equal(bill.baseCentavos,3600);assert.equal(bill.imageCentavos,900);assert.equal(bill.totalCentavos,4500)
 assert.deepEqual(bill.images,[2]);assert.equal(bill.monoPages,1);assert.equal(bill.colorPages,2)
 const reviewed=pricePages(pages,3,'Monochrome',200,500,setup,[1,2])
 assert.equal(reviewed.baseCentavos,1800);assert.equal(reviewed.imageCentavos,600)
})
