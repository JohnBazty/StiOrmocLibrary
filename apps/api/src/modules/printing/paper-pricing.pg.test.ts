import assert from 'node:assert/strict'
import test from 'node:test'
import { readFileSync } from 'node:fs'
import { PGlite } from '@electric-sql/pglite'
import { PDFDocument } from 'pdf-lib'
import { toPgPlaceholders } from '../../config/sql.js'
import { PrintingRepository } from './printing.repository.ts'
import { createPrintingService } from './printing.service.ts'
import { loadPaperBrand } from './paper-pricing.ts'
import { removePrintDocument } from './printing.storage.ts'

test('accepted printing keeps the loaded brand and price, while a changed quote is rejected under the stock lock', async () => {
 const pg=new PGlite(),stored:string[]=[]
 try {
  await pg.exec(`
   CREATE TABLE bond_paper_stocks(paper_stock_id bigint PRIMARY KEY,paper_size_dimension text,is_active boolean,deleted_at timestamptz,configuration_version int DEFAULT 1);
   CREATE TABLE paper_brand_stocks(paper_brand_stock_id bigint PRIMARY KEY,paper_stock_id bigint REFERENCES bond_paper_stocks,brand text,deleted_at timestamptz);
   CREATE TABLE print_pricing_rules(pricing_rule_id bigint,print_type text,paper_size text,price_per_page numeric(10,2),is_active int);
   CREATE TABLE print_supply_details(paper_stock_id bigint,width numeric,height numeric,dimension_unit text);
   CREATE TABLE print_requests(request_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,user_id bigint,file_name text,file_path text,number_of_copies int,print_type text,paper_size text,page_count int,total_sheets int,optional_notes text,calculated_cost numeric(12,2),payment_status text,job_status text);
   CREATE TABLE print_status_history(request_id bigint,from_status text,to_status text,changed_by_user_id bigint,reason text);
   INSERT INTO bond_paper_stocks VALUES(1,'A4',TRUE,NULL,1),(2,'A3',TRUE,NULL,1);
   INSERT INTO paper_brand_stocks VALUES(1,1,'Brand One',NULL),(2,1,'Brand Two',NULL),(3,2,'Other size',NULL);
   INSERT INTO print_pricing_rules VALUES(1,'Monochrome','A4',2,1),(2,'Colored','A4',5,1);
  `)
  await pg.exec(readFileSync(new URL('../../../../../database/supabase/051_loaded_paper_brand_prices.sql',import.meta.url),'utf8'))
  const execute=async(sql:string,args:unknown[]=[])=>{
   const write=/^\s*(INSERT|UPDATE|DELETE)/i.test(sql),insert=/^\s*INSERT/i.test(sql)
   const result=await pg.query<any>(toPgPlaceholders(sql)+(insert&&!/RETURNING/i.test(sql)?' RETURNING *':''),args)
   return [write?{insertId:Number(result.rows[0]?.request_id??0),affectedRows:result.affectedRows,rows:result.rows}:result.rows]
  }
  const connection={execute,beginTransaction:()=>pg.exec('BEGIN'),commit:()=>pg.exec('COMMIT'),rollback:()=>pg.exec('ROLLBACK'),release(){}}
  const pool={execute,getConnection:async()=>connection} as never,repo=new PrintingRepository(pool)
  let stale:unknown=null
  const repository={pricing:()=>stale??repo.pricing(),userBySchoolId:async()=>({user_id:7,account_status:'Active'}),serviceStatus:async()=>({accepting_requests:1})} as unknown as PrintingRepository
  const service=createPrintingService(pool,repository,null)
  await pg.exec('BEGIN');await loadPaperBrand(connection as never,1,1);await pg.exec('COMMIT')
  const document=await PDFDocument.create();document.addPage();document.addPage();const buffer=Buffer.from(await document.save())
  const file={originalname:'brand-price-qa.pdf',mimetype:'application/pdf',buffer,size:buffer.length} as Express.Multer.File
  const body={number_of_copies:2,print_type:'Monochrome',paper_size:'A4'}
  const quote=await service.quote({schoolId:'QA'},body,file)
  assert.equal(quote.calculated_cost,8);assert.equal(quote.paper_brand_stock_id,1)
  const accepted=await service.submit({schoolId:'QA'},{...body,quoted_cost:8,paper_brand_stock_id:1},file)
  let row=(await pg.query<any>('SELECT * FROM print_requests WHERE request_id=$1',[accepted.request_id])).rows[0]
  stored.push(row.file_path);assert.equal(row.paper_brand_snapshot,'Brand One');assert.equal(Number(row.unit_price_snapshot),2)
  stale=await repo.pricing()
  await pg.exec('BEGIN');await pg.query('UPDATE paper_brand_stocks SET monochrome_price=3,colored_price=6 WHERE paper_brand_stock_id=2');await loadPaperBrand(connection as never,1,2);await pg.exec('COMMIT')
  await assert.rejects(service.submit({schoolId:'QA'},{...body,quoted_cost:8,paper_brand_stock_id:1},file),{code:'PRINT_PRICE_CHANGED'})
  assert.equal((await pg.query('SELECT * FROM print_requests')).rows.length,1,'a stale quote cannot create a bill')
  stale=null
  const fresh=await service.quote({schoolId:'QA'},body,file)
  assert.equal(fresh.calculated_cost,12);assert.equal(fresh.paper_brand,'Brand Two')
  row=(await pg.query<any>('SELECT * FROM print_requests WHERE request_id=$1',[accepted.request_id])).rows[0]
  assert.equal(Number(row.calculated_cost),8);assert.equal(row.paper_brand_snapshot,'Brand One');assert.equal(Number(row.unit_price_snapshot),2)
  await assert.rejects(pg.query('UPDATE bond_paper_stocks SET loaded_paper_brand_stock_id=3 WHERE paper_stock_id=1'),{code:'23503'})
  await pg.query('UPDATE paper_brand_stocks SET monochrome_price=NULL WHERE paper_brand_stock_id=2')
  assert.equal((await repo.pricing()).some(row=>row.paper_size==='A4'&&row.print_type==='Monochrome'),false,'a missing loaded-brand rate cannot fall back to another brand')
 }finally{for(const file of stored)await removePrintDocument(file);await pg.close()}
})
