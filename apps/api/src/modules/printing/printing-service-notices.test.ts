import assert from 'node:assert/strict'
import test from 'node:test'
import { createNoticeTestDatabase } from '../notifications/user-notices.test.helper.ts'
import { createPrintingService } from './printing.service.ts'
import type { PrintingRepository } from './printing.repository.ts'

const DDL = `
CREATE TABLE users (user_id BIGINT PRIMARY KEY, user_role TEXT NOT NULL, full_name TEXT NOT NULL);
CREATE TABLE print_requests (request_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL, job_status TEXT NOT NULL);
CREATE TABLE printing_service_settings (
  settings_id SMALLINT NOT NULL PRIMARY KEY, accepting_requests INTEGER NOT NULL DEFAULT 1, unavailable_reason VARCHAR(255) DEFAULT NULL,
  updated_by_user_id BIGINT DEFAULT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP DEFAULT NULL);
INSERT INTO printing_service_settings (settings_id,accepting_requests) VALUES (1,1);
INSERT INTO users VALUES (9,'Staff','Libby Print-Staff'),(11,'Student','Ana Open-Student'),(12,'Faculty','Ben Open-Faculty'),(13,'Student','Cy Done-Student');
INSERT INTO print_requests (user_id,job_status) VALUES (11,'Pending'),(11,'Printing'),(12,'Ready for Pickup'),(13,'Completed'),(13,'Cancelled');`

const repository = { userBySchoolId: async () => ({ user_id: 9, account_status: 'Active' }) } as unknown as PrintingRepository
const actor = { schoolId: 'STAFF-9' }

async function fixture(extraDdl = '') {
  const { pg, pool } = await createNoticeTestDatabase(DDL + extraDdl)
  return { pg, pool, service: createPrintingService(pool, repository) }
}
const notices = async (pg: Awaited<ReturnType<typeof fixture>>['pg']) =>
  (await pg.query<Record<string, unknown>>('SELECT * FROM notifications ORDER BY notification_id')).rows
const setting = async (pg: Awaited<ReturnType<typeof fixture>>['pg']) =>
  (await pg.query<Record<string, unknown>>('SELECT accepting_requests, unavailable_reason FROM printing_service_settings WHERE settings_id=1')).rows[0]

test('pausing printing tells each user with an open request once, with the public reason (R6, D-04, D-09)', async () => {
  const { pg, service } = await fixture()
  const result = await service.setServiceStatus(actor, { accepting_requests: false, unavailable_reason: 'Out of paper' })
  assert.deepEqual(result, { accepting_requests: false, unavailable_reason: 'Out of paper' })
  assert.deepEqual(await setting(pg), { accepting_requests: 0, unavailable_reason: 'Out of paper' })
  const rows = await notices(pg)
  assert.deepEqual(rows.map(row => Number(row.user_id)), [11, 12])
  for (const row of rows) {
    assert.equal(row.message_title, 'Printing paused')
    assert.equal(row.message_body, 'Printing is paused: Out of paper. Your open requests are kept.')
    assert.equal(row.priority, 'Important'); assert.equal(row.trigger_type, 'Printing Update')
    assert.equal(row.source_type, 'Printing Service'); assert.equal(Number(row.source_id), 1)
    assert.match(String(row.dedupe_key), /^print-service:[0-9a-f-]{36}:paused$/)
  }
  assert.equal(rows[0].dedupe_key, rows[1].dedupe_key)
  assert.equal(rows[0].action_path, '/student/printing'); assert.equal(rows[1].action_path, '/faculty/notifications')
})

test('resuming printing gives the same users one Printing resumed notice (R7, D-05)', async () => {
  const { pg, service } = await fixture()
  await service.setServiceStatus(actor, { accepting_requests: false, unavailable_reason: 'Out of paper' })
  await service.setServiceStatus(actor, { accepting_requests: true })
  assert.deepEqual(await setting(pg), { accepting_requests: 1, unavailable_reason: null })
  const rows = await notices(pg)
  for (const userId of [11, 12]) {
    const own = rows.filter(row => Number(row.user_id) === userId)
    assert.deepEqual(own.map(row => row.message_title), ['Printing paused', 'Printing resumed'])
    assert.equal(own[1].message_body, 'Printing has resumed. Your open requests will continue.')
    assert.equal(own[1].priority, 'Normal'); assert.match(String(own[1].dedupe_key), /:resumed$/)
  }
  assert.equal(rows.length, 4)
})

test('a Staff user with an open request is linked to the staff printing page (D-10)', async () => {
  const { pg, service } = await fixture(`INSERT INTO users VALUES (14,'Staff','Dee Open-Staff'); INSERT INTO print_requests (user_id,job_status) VALUES (14,'Pending');`)
  await service.setServiceStatus(actor, { accepting_requests: false, unavailable_reason: 'Out of paper' })
  const rows = (await notices(pg)).filter(row => Number(row.user_id) === 14)
  assert.equal(rows.length, 1); assert.equal(rows[0].action_path, '/staff/printing')
})

test('no notice names the acting librarian or another user (P2)', async () => {
  const { pg, service } = await fixture()
  await service.setServiceStatus(actor, { accepting_requests: false, unavailable_reason: 'Out of paper' })
  await service.setServiceStatus(actor, { accepting_requests: true })
  for (const row of await notices(pg)) {
    for (const name of ['Libby', 'Ana', 'Ben', 'Cy ', 'Dee']) assert.ok(!String(row.message_body).includes(name) && !String(row.message_title).includes(name))
  }
})
