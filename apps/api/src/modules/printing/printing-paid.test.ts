import assert from 'node:assert/strict'
import { readFile } from 'node:fs/promises'
import test from 'node:test'
import { runMigrationInPglite } from '../../test-utils/pglite-migration.ts'
import { printingPaidSql } from './printing-paid.ts'

const migration = '055_printing_receivables_and_payment_review.sql'
const stubs = `
  CREATE TABLE users(user_id bigint PRIMARY KEY);
  CREATE TABLE accounts(account_id bigint PRIMARY KEY);
  CREATE TABLE print_requests(request_id bigint PRIMARY KEY, user_id bigint NOT NULL REFERENCES users,
    calculated_cost numeric(10,2) NOT NULL, payment_status text NOT NULL DEFAULT 'Unpaid');
  CREATE TABLE print_cash_payments(print_cash_payment_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_id bigint NOT NULL REFERENCES print_requests, amount_paid numeric(10,2) NOT NULL,
    received_by_user_id bigint REFERENCES users, received_at timestamp NOT NULL DEFAULT now(),
    CONSTRAINT uq_print_cash_request UNIQUE(request_id));
  CREATE TABLE print_payment_receipts(print_receipt_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    print_cash_payment_id bigint NOT NULL REFERENCES print_cash_payments,request_id bigint NOT NULL REFERENCES print_requests,
    amount_received numeric(10,2) NOT NULL,receipt_status text NOT NULL DEFAULT 'Issued',
    receipt_number varchar(32) NOT NULL,verification_code varchar(16) NOT NULL,
    CONSTRAINT uq_print_receipt_payment UNIQUE(print_cash_payment_id),
    CONSTRAINT uq_print_receipt_request UNIQUE(request_id),
    CONSTRAINT uq_print_receipt_number UNIQUE(receipt_number),
    CONSTRAINT uq_print_receipt_verification UNIQUE(verification_code));
  INSERT INTO users VALUES(1),(2);
  INSERT INTO accounts VALUES(1),(2);
  INSERT INTO print_requests VALUES(1,1,100,'Unpaid'),(2,1,100,'Paid'),(3,1,100,'Paid'),(4,1,100,'Paid');
  INSERT INTO print_cash_payments(request_id,amount_paid,received_by_user_id) VALUES(3,100,2),(4,100,2);
  INSERT INTO print_payment_receipts(print_cash_payment_id,request_id,amount_received,receipt_status,receipt_number,verification_code)
    VALUES(1,3,100,'Reversed','PR-OLD','OLD-CODE');
`

test('055 preserves history, permits separate partial receipts, retains receipt uniqueness and excludes reversals', async t => {
  const db = await runMigrationInPglite(migration,stubs)
  t.after(() => db.close())
  const paid = () => db.queryAs('library_owner',`SELECT pr.request_id,${printingPaidSql()} AS paid FROM print_requests pr ORDER BY pr.request_id`)
  assert.deepEqual((await paid()).rows.map(row => Number(row.paid)),[0,100,0,100])
  await db.queryAs('library_owner',`INSERT INTO print_cash_payments(request_id,amount_paid,received_by_user_id,request_key)
    VALUES(1,40,2,'00000000-0000-0000-0000-000000000001')`)
  await db.queryAs('library_owner',`INSERT INTO print_payment_receipts(print_cash_payment_id,request_id,amount_received,receipt_number,verification_code,balance_before,balance_after)
    VALUES(3,1,40,'PR-40','CODE-40',100,60)`)
  assert.equal(Number((await paid()).rows[0].paid),40)
  await db.queryAs('library_owner',`INSERT INTO print_cash_payments(request_id,amount_paid,received_by_user_id,request_key)
    VALUES(1,60,2,'00000000-0000-0000-0000-000000000002')`)
  await db.queryAs('library_owner',`INSERT INTO print_payment_receipts(print_cash_payment_id,request_id,amount_received,receipt_number,verification_code,balance_before,balance_after)
    VALUES(4,1,60,'PR-60','CODE-60',60,0)`)
  assert.equal(Number((await paid()).rows[0].paid),100)
  await assert.rejects(db.queryAs('library_owner',`INSERT INTO print_cash_payments(request_id,amount_paid,request_key) VALUES(1,60,'00000000-0000-0000-0000-000000000002')`),/duplicate key/)
  await assert.rejects(db.queryAs('library_owner',`INSERT INTO print_payment_receipts(print_cash_payment_id,request_id,amount_received,receipt_number,verification_code) VALUES(4,1,60,'PR-DUP','CODE-DUP')`),/uq_print_receipt_payment/)
  await db.queryAs('library_owner',`UPDATE print_payment_receipts SET receipt_status='Reversed' WHERE receipt_number='PR-40'`)
  assert.equal(Number((await paid()).rows[0].paid),60)
  const old = await db.queryAs('library_owner',`SELECT amount_received,receipt_status,receipt_number FROM print_payment_receipts WHERE print_receipt_id=1`)
  assert.deepEqual(old.rows,[{amount_received:'100.00',receipt_status:'Reversed',receipt_number:'PR-OLD'}])
  const sql = await readFile(new URL('../../../../../database/supabase/'+migration,import.meta.url),'utf8')
  const rerun = await runMigrationInPglite(migration,stubs+sql)
  t.after(()=>rerun.close())
  assert.deepEqual((await rerun.queryAs('library_owner',`SELECT pr.request_id,${printingPaidSql()} paid FROM print_requests pr ORDER BY request_id`)).rows.map(row=>Number(row.paid)),[0,100,0,100])
})

const privateTables = ['print_deferred_approvals','print_deferred_events','gcash_payment_settings','gcash_payment_setting_events',
  'print_payment_proofs','print_proof_events','library_service_charges','library_service_cash_payments']

test('055 denies browser roles and retains owner access even when a SELECT grant returns', async t => {
  const db = await runMigrationInPglite(migration,stubs)
  t.after(() => db.close())
  for(const table of privateTables){
    for(const role of ['anon','authenticated']) await assert.rejects(db.queryAs(role,`SELECT * FROM ${table}`),/permission denied/)
    const rls = await db.queryAs('library_owner',`SELECT relrowsecurity FROM pg_class WHERE oid='${table}'::regclass`)
    assert.equal(rls.rows[0].relrowsecurity,true,table)
    await db.queryAs('library_owner',`SELECT * FROM ${table}`)
    await db.queryAs('library_owner',`GRANT SELECT ON ${table} TO anon,authenticated`)
    for(const role of ['anon','authenticated']) assert.deepEqual((await db.queryAs(role,`SELECT * FROM ${table}`)).rows,[],table)
  }
})

test('055 proof identity, active submission and verified-reference guards reject duplicate evidence without preclaiming pending references',async t=>{
  const db=await runMigrationInPglite(migration,stubs)
  t.after(()=>db.close())
  const proof=(id:number,payment:number,status:string)=>`INSERT INTO print_payment_proofs(proof_id,request_id,user_id,payment_id,external_reference,declared_amount,storage_key,mime_type,byte_size,sha256,review_status,request_key)
    VALUES('00000000-0000-0000-0000-${String(id).padStart(12,'0')}',1,1,'00000000-0000-0000-0000-${String(payment).padStart(12,'0')}','REFERENCE',100,'proof/${id}','image/png',10,repeat('a',64),'${status}','10000000-0000-0000-0000-${String(id).padStart(12,'0')}')`
  await db.queryAs('library_owner',proof(1,1,'Pending'))
  await db.queryAs('library_owner',proof(2,2,'Pending'))
  await assert.rejects(db.queryAs('library_owner',proof(3,1,'Pending')),/duplicate key/)
  await db.queryAs('library_owner',`UPDATE print_payment_proofs SET review_status='Verified',reviewed_by_user_id=2,reviewed_at=now() WHERE storage_key='proof/1'`)
  await assert.rejects(db.queryAs('library_owner',`UPDATE print_payment_proofs SET review_status='Verified',reviewed_by_user_id=2,reviewed_at=now() WHERE storage_key='proof/2'`),/duplicate key/)
  assert.deepEqual((await db.queryAs('library_owner',`SELECT ${printingPaidSql()} paid FROM print_requests pr WHERE request_id=1`)).rows,[{paid:'0'}])
})

test('055 keeps debt approvals and new service receipts explicit, audited and separate from printing money',async t=>{
  const db=await runMigrationInPglite(migration,stubs)
  t.after(()=>db.close())
  await db.queryAs('library_owner',`INSERT INTO print_deferred_approvals(request_id,approved_by_user_id,reason,assessed_amount,request_key)
    VALUES(1,2,'Authorized counter balance',100,'00000000-0000-0000-0000-000000000001')`)
  await assert.rejects(db.queryAs('library_owner',`UPDATE print_deferred_approvals SET acknowledged_at=now() WHERE request_id=1`),/check constraint/)
  await db.queryAs('library_owner',`UPDATE print_deferred_approvals SET acknowledged_at=now(),acknowledged_by_account_id=1 WHERE request_id=1`)
  await assert.rejects(db.queryAs('library_owner',`UPDATE print_deferred_approvals SET revoked_at=now(),revoked_by_user_id=2 WHERE request_id=1`),/check constraint/)
  await db.queryAs('library_owner',`INSERT INTO library_service_charges(user_id,description,amount_assessed,created_by_user_id,request_key)
    VALUES(1,'Document finishing charge',100,2,'00000000-0000-0000-0000-000000000002')`)
  const receipt=(amount:number,before:number,after:number,key:number)=>`INSERT INTO library_service_cash_payments(charge_id,amount_paid,request_key,received_by_user_id,
    receipt_number,verification_code,student_name_snapshot,school_id_snapshot,description_snapshot,received_by_name_snapshot,balance_before,balance_after)
    VALUES(1,${amount},'00000000-0000-0000-0000-${String(key).padStart(12,'0')}',2,'SC-${key}','VC-${key}','Borrower fixture','FIXTURE-1','Document finishing charge','Staff fixture',${before},${after})`
  await assert.rejects(db.queryAs('library_owner',receipt(0,100,100,3)),/check constraint/)
  await assert.rejects(db.queryAs('library_owner',receipt(40,100,70,4)),/check constraint/)
  await db.queryAs('library_owner',receipt(40,100,60,5))
  await db.queryAs('library_owner',receipt(60,60,0,6))
  await assert.rejects(db.queryAs('library_owner',`UPDATE library_service_cash_payments SET receipt_status='Reversed',reversed_by_user_id=2,reversed_at=now() WHERE service_payment_id=3`),/check constraint/)
  const totals=await db.queryAs('library_owner',`SELECT SUM(amount_paid) paid FROM library_service_cash_payments WHERE receipt_status='Issued'`)
  assert.equal(Number(totals.rows[0].paid),100)
  assert.equal(Number((await db.queryAs('library_owner',`SELECT ${printingPaidSql()} paid FROM print_requests pr WHERE request_id=1`)).rows[0].paid),0)
  for(const sequence of ['print_deferred_events_event_id_seq','gcash_payment_setting_events_event_id_seq','print_proof_events_event_id_seq',
    'library_service_charges_charge_id_seq','library_service_cash_payments_service_payment_id_seq']){
    for(const role of ['anon','authenticated']){
      const result=await db.queryAs('library_owner',`SELECT has_sequence_privilege('${role}','${sequence}','USAGE') AS allowed`)
      assert.equal(result.rows[0].allowed,false,`${role}:${sequence}`)
    }
  }
})

