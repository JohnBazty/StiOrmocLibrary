import assert from 'node:assert/strict'
import test from 'node:test'
import { runMigrationInPglite } from '../../test-utils/pglite-migration.ts'

const stubs = `
  CREATE TABLE catalog_locations (
    location_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(100) NOT NULL UNIQUE,
    lifecycle_status text NOT NULL DEFAULT 'Active', row_version integer NOT NULL DEFAULT 1,
    created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now()
  );
  CREATE TABLE floor_plan_shelves (id bigint PRIMARY KEY, label varchar(100), column_count smallint, row_count smallint);
  CREATE TABLE categories (category_id bigint PRIMARY KEY, shelf_location varchar(100), shelf_column smallint, shelf_row smallint);
  CREATE TABLE physical_copies (physical_copy_id bigint PRIMARY KEY, shelf_location varchar(100), shelf_column smallint, shelf_row smallint, lifecycle_status text);
  CREATE TABLE research_inventory (research_inventory_id bigint PRIMARY KEY, shelf_location varchar(100), shelf_column smallint, shelf_row smallint, lifecycle_status text);
  INSERT INTO catalog_locations(name,lifecycle_status,row_version) VALUES
    ('Shelf A','Active',7),('Empty shelf','Active',2),('Retired shelf','Archived',4);
  INSERT INTO floor_plan_shelves VALUES (1,'Shelf A',3,5),(2,'Old floor shelf',2,4);
  INSERT INTO categories VALUES (1,'Shelf A',4,2),(2,'Category-only shelf',2,3);
  INSERT INTO physical_copies VALUES (1,'Shelf A',2,6,'Active'),(2,'Shelf A',5,2,'Archived');
  INSERT INTO research_inventory VALUES (1,'Shelf A',1,7,'Active'),(2,'Research-only shelf',3,4,'Archived');
  RESET ROLE;
  CREATE SCHEMA unrelated_project AUTHORIZATION library_owner;
  SET ROLE library_owner;
  CREATE TABLE unrelated_project.untouched (value text);
  INSERT INTO unrelated_project.untouched VALUES ('preserved');
`

test('046 preserves assignments and backfills authoritative dimensions without inventing capacity', async (t) => {
  const db = await runMigrationInPglite('066_shelf_capacity.sql', stubs)
  t.after(() => db.close())
  const locations = await db.queryAs('library_owner', `SELECT name,column_count,row_count,default_capacity,lifecycle_status,row_version FROM catalog_locations ORDER BY name`)
  assert.deepEqual(locations.rows, [
    { name: 'Category-only shelf', column_count: 2, row_count: 3, default_capacity: null, lifecycle_status: 'Active', row_version: 1 },
    { name: 'Empty shelf', column_count: 1, row_count: 1, default_capacity: null, lifecycle_status: 'Active', row_version: 2 },
    { name: 'Old floor shelf', column_count: 2, row_count: 4, default_capacity: null, lifecycle_status: 'Active', row_version: 1 },
    { name: 'Research-only shelf', column_count: 3, row_count: 4, default_capacity: null, lifecycle_status: 'Active', row_version: 1 },
    { name: 'Retired shelf', column_count: 1, row_count: 1, default_capacity: null, lifecycle_status: 'Archived', row_version: 4 },
    { name: 'Shelf A', column_count: 5, row_count: 7, default_capacity: null, lifecycle_status: 'Active', row_version: 7 },
  ])
  assert.deepEqual((await db.queryAs('library_owner', 'SELECT * FROM physical_copies ORDER BY physical_copy_id')).rows, [
    { physical_copy_id: 1, shelf_location: 'Shelf A', shelf_column: 2, shelf_row: 6, lifecycle_status: 'Active' },
    { physical_copy_id: 2, shelf_location: 'Shelf A', shelf_column: 5, shelf_row: 2, lifecycle_status: 'Archived' },
  ])
  assert.deepEqual((await db.queryAs('library_owner', 'SELECT * FROM categories ORDER BY category_id')).rows, [
    { category_id: 1, shelf_location: 'Shelf A', shelf_column: 4, shelf_row: 2 },
    { category_id: 2, shelf_location: 'Category-only shelf', shelf_column: 2, shelf_row: 3 },
  ])
  assert.deepEqual((await db.queryAs('library_owner', 'SELECT * FROM research_inventory ORDER BY research_inventory_id')).rows, [
    { research_inventory_id: 1, shelf_location: 'Shelf A', shelf_column: 1, shelf_row: 7, lifecycle_status: 'Active' },
    { research_inventory_id: 2, shelf_location: 'Research-only shelf', shelf_column: 3, shelf_row: 4, lifecycle_status: 'Archived' },
  ])
  assert.deepEqual((await db.queryAs('library_owner', 'SELECT * FROM floor_plan_shelves ORDER BY id')).rows, [
    { id: 1, label: 'Shelf A', column_count: 3, row_count: 5 },
    { id: 2, label: 'Old floor shelf', column_count: 2, row_count: 4 },
  ])
  assert.equal((await db.queryAs('library_owner', 'SELECT count(*)::int AS n FROM catalog_location_capacities')).rows[0].n, 0)
  assert.deepEqual((await db.queryAs('library_owner', 'SELECT * FROM unrelated_project.untouched')).rows, [{ value: 'preserved' }])
})

test('046 keeps capacity overrides API-only and enforces positive capacities and unique coordinates', async (t) => {
  const db = await runMigrationInPglite('066_shelf_capacity.sql', stubs)
  t.after(() => db.close())
  for (const role of ['anon', 'authenticated']) {
    await assert.rejects(db.queryAs(role, 'SELECT * FROM catalog_location_capacities'), /permission denied/)
    await assert.rejects(db.queryAs(role, 'INSERT INTO catalog_location_capacities VALUES (1,1,1,20)'), /permission denied/)
  }
  await db.queryAs('library_owner', 'INSERT INTO catalog_location_capacities VALUES (1,1,1,20)')
  assert.equal((await db.queryAs('service_role', 'SELECT count(*)::int AS n FROM catalog_location_capacities')).rows[0].n, 1)
  assert.equal((await db.queryAs('library_owner', `SELECT relrowsecurity FROM pg_class WHERE oid='public.catalog_location_capacities'::regclass`)).rows[0].relrowsecurity, true)
  await db.queryAs('library_owner', 'GRANT SELECT ON catalog_location_capacities TO anon,authenticated')
  for (const role of ['anon', 'authenticated']) {
    assert.equal((await db.queryAs(role, 'SELECT count(*)::int AS n FROM catalog_location_capacities')).rows[0].n, 0)
  }
  for (const sql of [
    'INSERT INTO catalog_location_capacities VALUES (1,1,1,30)',
    'INSERT INTO catalog_location_capacities VALUES (1,0,1,20)',
    'INSERT INTO catalog_location_capacities VALUES (1,1,13,20)',
    'INSERT INTO catalog_location_capacities VALUES (1,2,1,0)',
    'INSERT INTO catalog_location_capacities VALUES (999,1,1,20)',
    'UPDATE catalog_locations SET column_count=0 WHERE location_id=1',
    'UPDATE catalog_locations SET row_count=13 WHERE location_id=1',
    'UPDATE catalog_locations SET default_capacity=0 WHERE location_id=1',
  ]) await assert.rejects(db.queryAs('library_owner', sql), /constraint/)
  await db.queryAs('library_owner', 'UPDATE catalog_locations SET default_capacity=25 WHERE location_id=1')
  assert.equal((await db.queryAs('library_owner', 'SELECT default_capacity FROM catalog_locations WHERE location_id=1')).rows[0].default_capacity, 25)
})

