/**
 * Real Postgres (PGlite) with the tables damage cases touch, trimmed to the columns the code uses,
 * plus the applied `017_circulation_cases.sql` migration as-is.
 */
export async function createCaseTestDatabase() {
  const pg = new PGlite()
  await pg.exec(`
    CREATE TABLE users (user_id BIGINT PRIMARY KEY, school_id TEXT NOT NULL, full_name TEXT NOT NULL, account_status TEXT NOT NULL DEFAULT 'Active');
    CREATE TABLE accounts (account_id BIGINT PRIMARY KEY, user_id BIGINT NULL REFERENCES users(user_id), role TEXT NOT NULL, account_status TEXT NOT NULL DEFAULT 'Active');
    CREATE TABLE titles (title_id BIGINT PRIMARY KEY, title TEXT NOT NULL, purchase_price DECIMAL(10,2) NULL);
    CREATE TABLE materials (material_id BIGINT PRIMARY KEY, title TEXT NOT NULL, availability_status TEXT NOT NULL DEFAULT 'Available', updated_at TIMESTAMP NULL);
    CREATE TABLE physical_copies (physical_copy_id BIGINT PRIMARY KEY, title_id BIGINT NOT NULL REFERENCES titles(title_id), material_id BIGINT NULL,
      barcode TEXT NOT NULL UNIQUE, accession_number TEXT NULL, condition_status TEXT NOT NULL DEFAULT 'Good',
      availability_status TEXT NOT NULL DEFAULT 'Available', lifecycle_status TEXT NOT NULL DEFAULT 'Active',
      row_version INT NOT NULL DEFAULT 0, updated_at TIMESTAMP NULL);
    CREATE TABLE borrowing_policy_versions (borrowing_policy_version_id BIGINT PRIMARY KEY);
    CREATE TABLE borrow_transactions (transaction_id BIGINT PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(user_id),
      material_id BIGINT NULL, physical_copy_id BIGINT NOT NULL REFERENCES physical_copies(physical_copy_id),
      transaction_status TEXT NOT NULL, due_at TIMESTAMP NULL, returned_at TIMESTAMP NULL, lost_confirmed_at TIMESTAMP NULL, updated_at TIMESTAMP NULL);
    CREATE TABLE lost_book_reports (lost_book_report_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      transaction_id BIGINT NOT NULL UNIQUE REFERENCES borrow_transactions(transaction_id), user_id BIGINT NOT NULL, physical_copy_id BIGINT NULL,
      report_status TEXT NOT NULL DEFAULT 'Pending', purchase_price_snapshot DECIMAL(10,2) NULL, replacement_charge DECIMAL(10,2) NOT NULL DEFAULT 0,
      payment_status TEXT NOT NULL DEFAULT 'Unpaid', reported_at TIMESTAMP NOT NULL, verified_by_user_id BIGINT NULL, verified_at TIMESTAMP NULL,
      staff_notes VARCHAR(500) NULL, quotation_id BIGINT NULL, charge_resolution VARCHAR(24) NOT NULL DEFAULT 'Awaiting Review',
      resolution_reason VARCHAR(500) NULL, updated_at TIMESTAMP NULL);
    CREATE TABLE fines (fine_id BIGSERIAL PRIMARY KEY, transaction_id BIGINT UNIQUE, fine_amount DECIMAL(10,2) NOT NULL, payment_status TEXT NOT NULL);
    CREATE TABLE notifications (notification_id BIGSERIAL PRIMARY KEY, user_id BIGINT NOT NULL, message_title TEXT NOT NULL, message_body TEXT NOT NULL,
      trigger_type TEXT NOT NULL, source_type TEXT NULL, source_id BIGINT NULL, action_path TEXT NULL, priority TEXT NULL, dedupe_key TEXT NULL,
      scheduled_for TIMESTAMP NULL, delivered_at TIMESTAMP NULL, UNIQUE (user_id, dedupe_key));
    CREATE TABLE admin_notifications (admin_notification_id BIGSERIAL PRIMARY KEY, event_type TEXT NOT NULL, actor_user_id BIGINT NULL,
      borrow_transaction_id BIGINT NULL, message_title TEXT NOT NULL, message_body TEXT NOT NULL);
    CREATE TABLE inventory_audit_events (inventory_audit_event_id BIGSERIAL PRIMARY KEY, physical_copy_id BIGINT NOT NULL, barcode_snapshot TEXT NOT NULL,
      event_type TEXT NOT NULL, previous_condition TEXT NULL, new_condition TEXT NULL, previous_availability TEXT NULL, new_availability TEXT NULL,
      verified_by_user_id BIGINT NULL, verified_by_label TEXT NULL, action_reason TEXT NULL);
  `)
  await pg.exec(readFileSync(new URL('../../../../../database/supabase/017_circulation_cases.sql', import.meta.url), 'utf8'))
  await pg.exec(readFileSync(new URL('../../../../../database/supabase/037_book_register.sql', import.meta.url), 'utf8'))
  await pg.exec(`
    INSERT INTO users VALUES (7,'STI-7','Borrower Seven','Active'),(8,'STI-8','Borrower Eight','Active'),(2,'LIB-2','Librarian Two','Active'),(3,'STF-3','Staff Three','Active');
    INSERT INTO accounts VALUES (20,2,'Librarian','Active'),(30,3,'Staff','Active');
    INSERT INTO titles VALUES (10,'Clean Code',450.00),(11,'Old Atlas',NULL);
    INSERT INTO materials VALUES (100,'Clean Code','Unavailable'),(101,'Old Atlas','Unavailable');
    INSERT INTO physical_copies (physical_copy_id,title_id,material_id,barcode,accession_number,condition_status,availability_status)
      VALUES (50,10,100,'BOOK-50','ACC-50','Damaged','Unavailable'),(51,11,101,'BOOK-51','ACC-51','Damaged','Unavailable');
    INSERT INTO borrow_transactions (transaction_id,user_id,material_id,physical_copy_id,transaction_status,returned_at)
      VALUES (900,7,100,50,'Returned',NOW()),(901,8,101,51,'Returned',NOW());
  `)
  const execute = async (sql: string, values: unknown[] = []) => {
    const insert = /^\s*INSERT/i.test(sql) && !/\bRETURNING\b/i.test(sql)
    const result = await pg.query(toPgPlaceholders(insert ? `${sql.replace(/;?\s*$/, '')} RETURNING *` : sql), values)
    const write = /^\s*(INSERT|UPDATE|DELETE)/i.test(sql)
    if (!write) return [result.rows, result]
    const first = result.rows[0] as Record<string, unknown> | undefined
    const insertId = first ? Number(Object.values(first)[0]) : 0
    return [{ affectedRows: result.affectedRows ?? 0, insertId, rows: result.rows }, result]
  }
  const connection = { execute, query: execute, beginTransaction: () => pg.exec('BEGIN'), commit: () => pg.exec('COMMIT'), rollback: () => pg.exec('ROLLBACK'), release() {} }
  const pool = { execute, query: execute, getConnection: async () => connection } as unknown as Pool
  return { pg, pool, connection }
}

