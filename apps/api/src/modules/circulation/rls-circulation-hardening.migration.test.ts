import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import test from 'node:test'
import { PGlite } from '@electric-sql/pglite'

const migration = readFileSync(new URL('../../../../../database/supabase/035_rls_circulation_hardening.sql', import.meta.url), 'utf8')
const tables = ['borrow_transactions', 'physical_copies', 'reservations']

test('035 locks the circulation tables to the server, keeps the owner working, and can run twice', async () => {
  const pg = new PGlite()
  // Real key columns from 001_from_baseline.sql and 002_from_migrations.sql.
  await pg.exec(`CREATE ROLE anon; CREATE ROLE authenticated;
    CREATE TABLE borrow_transactions (transaction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT);
    CREATE TABLE reservations (reservation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT);
    CREATE TABLE physical_copies (physical_copy_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, barcode TEXT);
    GRANT SELECT, INSERT ON borrow_transactions, reservations, physical_copies TO anon, authenticated`)
  await pg.exec(migration)
  await pg.exec(migration)

  const rls = await pg.query<{ relname: string; relrowsecurity: boolean }>(
    `SELECT relname, relrowsecurity FROM pg_class WHERE relname = ANY($1) ORDER BY relname`, [tables])
  assert.deepEqual(rls.rows, tables.map(relname => ({ relname, relrowsecurity: true })))
  const grants = await pg.query<{ granted: boolean }>(
    `SELECT bool_or(has_table_privilege(r, t, 'SELECT') OR has_table_privilege(r, t, 'INSERT')) AS granted
     FROM unnest(ARRAY['anon', 'authenticated']) r, unnest($1::text[]) t`, [tables])
  assert.equal(grants.rows[0].granted, false)
  // The table owner (the API's server connection) is not blocked by RLS.
  await pg.exec("INSERT INTO physical_copies (barcode) VALUES ('BC-1')")
  const owner = await pg.query<{ count: number }>('SELECT count(*)::int AS count FROM physical_copies')
  assert.equal(owner.rows[0].count, 1)
  await pg.close()
})
