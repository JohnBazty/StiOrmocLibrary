import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import test from 'node:test'
import { PGlite } from '@electric-sql/pglite'

const migration = readFileSync(new URL('../../../../../database/supabase/035_rls_circulation_hardening.sql', import.meta.url), 'utf8')
const tables = ['borrow_transactions', 'physical_copies', 'reservations']

// Real key columns from 001_from_baseline.sql and 002_from_migrations.sql.
const schema = `CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role;
  CREATE TABLE borrow_transactions (transaction_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT);
  CREATE TABLE reservations (reservation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT);
  CREATE TABLE physical_copies (physical_copy_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, barcode TEXT);
  GRANT SELECT, INSERT ON borrow_transactions, reservations, physical_copies TO PUBLIC, anon, authenticated;
  GRANT USAGE ON ALL SEQUENCES IN SCHEMA public TO PUBLIC, anon, authenticated`

test('035 locks the circulation tables to the server, keeps the owner working, and can run twice', async () => {
  const pg = new PGlite()
  await pg.exec(schema)
  await pg.exec(migration)
  await pg.exec(migration)

  const rls = await pg.query<{ relname: string; relrowsecurity: boolean }>(
    'SELECT relname, relrowsecurity FROM pg_class WHERE relname = ANY($1) ORDER BY relname', [tables])
  assert.deepEqual(rls.rows, tables.map(relname => ({ relname, relrowsecurity: true })))
  const grants = await pg.query<{ granted: boolean }>(
    `SELECT bool_or(has_table_privilege(r, t, 'SELECT') OR has_table_privilege(r, t, 'INSERT')) AS granted
     FROM unnest(ARRAY['anon', 'authenticated']) r, unnest($1::text[]) t`, [tables])
  assert.equal(grants.rows[0].granted, false)
  const sequences = await pg.query<{ granted: boolean }>(
    `SELECT bool_or(has_sequence_privilege(r, s, 'USAGE')) AS granted FROM unnest(ARRAY['anon', 'authenticated']) r,
     unnest(ARRAY[pg_get_serial_sequence('borrow_transactions', 'transaction_id'), pg_get_serial_sequence('reservations', 'reservation_id'),
       pg_get_serial_sequence('physical_copies', 'physical_copy_id')]) s`)
  assert.equal(sequences.rows[0].granted, false)
  const policies = await pg.query<{ count: number }>("SELECT count(*)::int AS count FROM pg_policies WHERE policyname = 'service_role_all'")
  assert.equal(policies.rows[0].count, 3)

  // The owner (the API's server connection) still reads; a granted non-owner sees no rows.
  await pg.exec("INSERT INTO physical_copies (barcode) VALUES ('BC-1'); CREATE ROLE reader; GRANT SELECT ON physical_copies TO reader")
  assert.equal((await pg.query<{ count: number }>('SELECT count(*)::int AS count FROM physical_copies')).rows[0].count, 1)
  await pg.exec('SET ROLE reader')
  assert.equal((await pg.query<{ count: number }>('SELECT count(*)::int AS count FROM physical_copies')).rows[0].count, 0)
  await pg.close()
})

test('035 refuses a role that neither owns the tables nor bypasses RLS', async () => {
  const pg = new PGlite()
  await pg.exec(`${schema}; CREATE ROLE migrator; GRANT ALL ON SCHEMA public TO migrator; SET ROLE migrator`)
  await assert.rejects(pg.exec(migration), /neither owns borrow_transactions nor bypasses RLS/)
  await pg.close()
})
