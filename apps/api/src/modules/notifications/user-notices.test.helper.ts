import { PGlite } from '@electric-sql/pglite'
import type { Pool } from '../../config/db.js'
import { toPgPlaceholders } from '../../config/sql.js'

/** Real Postgres (PGlite) with the notifications table of 001_from_baseline.sql, minus the users foreign key. */
export async function createNoticeTestDatabase(ddl = '') {
  const pg = new PGlite()
  await pg.exec(`CREATE TABLE notifications (
    notification_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    message_title VARCHAR(150) NOT NULL,
    message_body TEXT NOT NULL,
    trigger_type TEXT NOT NULL,
    source_type VARCHAR(40) DEFAULT NULL,
    source_id BIGINT DEFAULT NULL,
    action_path VARCHAR(255) DEFAULT NULL,
    priority TEXT NOT NULL DEFAULT 'Normal',
    dedupe_key VARCHAR(191) DEFAULT NULL,
    scheduled_for TIMESTAMP DEFAULT NULL,
    delivered_at TIMESTAMP DEFAULT NULL,
    expires_at TIMESTAMP DEFAULT NULL,
    is_read INTEGER NOT NULL DEFAULT 0,
    notification_timestamp TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    read_at TIMESTAMP DEFAULT NULL,
    CONSTRAINT uq_notification_user_dedupe UNIQUE (user_id, dedupe_key)
  )`)
  if (ddl) await pg.exec(ddl)
  const execute = async (sql: string, values: unknown[] = []) => {
    const result = await pg.query(toPgPlaceholders(sql), values)
    const write = /^\s*(INSERT|UPDATE|DELETE)/i.test(sql)
    return write ? [{ affectedRows: result.affectedRows ?? 0, rows: result.rows }, result] : [result.rows, result]
  }
  const connection = { execute, query: execute, beginTransaction: () => pg.exec('BEGIN'), commit: () => pg.exec('COMMIT'), rollback: () => pg.exec('ROLLBACK'), release() {} }
  const pool = { execute, query: execute, getConnection: async () => connection } as unknown as Pool
  return { pg, pool }
}
