-- Synthetic local app bootstrap only; never a hosted migration.
-- Four reviewed normalized catalog definitions from the historical design.
-- No backfills, old triggers, data copies or old migration replay.

CREATE TABLE IF NOT EXISTS titles (
  title_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  category_id INTEGER DEFAULT NULL,
  record_type TEXT NOT NULL,
  title VARCHAR(255) NOT NULL,
  normalized_title VARCHAR(255) NOT NULL,
  isbn VARCHAR(17) DEFAULT NULL,
  publication_year INTEGER DEFAULT NULL,
  publisher VARCHAR(255) DEFAULT NULL,
  call_number VARCHAR(100) DEFAULT NULL,
  cover_image_path VARCHAR(500) DEFAULT NULL,
  search_text TEXT,
  lifecycle_status TEXT NOT NULL DEFAULT 'Active',
  archived_at TIMESTAMP DEFAULT NULL,
  archive_reason VARCHAR(255) DEFAULT NULL,
  row_version INTEGER NOT NULL DEFAULT 1,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT NULL,
  PRIMARY KEY (title_id),
  CONSTRAINT uq_titles_isbn UNIQUE (isbn),
  CONSTRAINT fk_titles_category
    FOREIGN KEY (category_id) REFERENCES categories (category_id)
    ON UPDATE CASCADE ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS authors (
  author_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  title_id BIGINT NOT NULL,
  author_name VARCHAR(255) NOT NULL,
  normalized_name VARCHAR(191) NOT NULL,
  author_order INTEGER NOT NULL DEFAULT 1,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT NULL,
  PRIMARY KEY (author_id),
  CONSTRAINT uq_authors_title_name UNIQUE (title_id, normalized_name),
  CONSTRAINT uq_authors_title_order UNIQUE (title_id, author_order)
);

CREATE TABLE IF NOT EXISTS research_records (
  research_record_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  title_id BIGINT NOT NULL,
  research_code VARCHAR(100) NOT NULL,
  adviser_name VARCHAR(255) NOT NULL,
  department_or_program VARCHAR(150) NOT NULL,
  abstract_text TEXT NOT NULL,
  keywords_text TEXT,
  viewing_status
    TEXT
    NOT NULL DEFAULT 'Available for Viewing',
  last_scanned_at TIMESTAMP DEFAULT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT NULL,
  PRIMARY KEY (research_record_id),
  CONSTRAINT uq_research_records_title_id UNIQUE (title_id),
  CONSTRAINT uq_research_records_code UNIQUE (research_code)
);

CREATE TABLE IF NOT EXISTS physical_copies (
  physical_copy_id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  title_id BIGINT NOT NULL,
  material_id BIGINT DEFAULT NULL,
  barcode VARCHAR(100) NOT NULL,
  accession_number VARCHAR(100) NOT NULL,
  shelf_location VARCHAR(100) NOT NULL,
  condition_status
    TEXT
    NOT NULL DEFAULT 'Good',
  availability_status
    TEXT
    NOT NULL DEFAULT 'Available',
  lifecycle_status TEXT NOT NULL DEFAULT 'Active',
  acquired_at DATE DEFAULT NULL,
  last_scanned_at TIMESTAMP DEFAULT NULL,
  archived_at TIMESTAMP DEFAULT NULL,
  archive_reason VARCHAR(255) DEFAULT NULL,
  row_version INTEGER NOT NULL DEFAULT 1,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP DEFAULT NULL,
  PRIMARY KEY (physical_copy_id),
  CONSTRAINT uq_physical_copies_material_id UNIQUE (material_id),
  CONSTRAINT uq_physical_copies_barcode UNIQUE (barcode),
  CONSTRAINT uq_physical_copies_accession UNIQUE (accession_number)
);
