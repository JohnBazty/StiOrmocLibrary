it('return actions open a review and update tasks only after confirmation',async()=>{
 open();await screen.findByText('Ana Flores')
 const initial=vi.mocked(deskDashboardApi.tasks).mock.calls.length
 fireEvent.click(screen.getAllByRole('button',{name:'Return book'})[0])
 expect(screen.getByRole('dialog',{name:'Return review'})).toBeTruthy()
 expect(deskDashboardApi.tasks).toHaveBeenCalledTimes(initial)
 fireEvent.click(screen.getByRole('button',{name:'Confirm return'}))
 await screen.findByText('Book returned.')
 await waitFor(()=>expect(deskDashboardApi.tasks).toHaveBeenCalledTimes(initial+1))
})

