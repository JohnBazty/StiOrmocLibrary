const open=()=>render(<MemoryRouter><AdminDashboardPage/></MemoryRouter>)
it('shows analytics and daily tasks without the embedded counter or universal search',async()=>{
 open();await screen.findByText('Ana Flores')
 await screen.findByRole('heading',{name:'Weekly attendance'})
 const sections=screen.getAllByRole('region').filter(el=>['Instant circulation','Daily action cards'].includes(el.getAttribute('aria-label')??'')||['dashboard-analytics-heading','desk-tasks-heading','collection-snapshot-heading'].includes(el.getAttribute('aria-labelledby')??''))
 expect(sections.map(el=>el.getAttribute('aria-label')??el.getAttribute('aria-labelledby'))).toEqual(['Daily action cards','desk-tasks-heading','dashboard-analytics-heading','collection-snapshot-heading'])
 expect(screen.queryByRole('region',{name:'Instant circulation'})).toBeNull()
 expect(screen.queryByLabelText('Find a student or book')).toBeNull()
 expect(screen.queryByPlaceholderText('Name, School ID, book title or ISBN')).toBeNull()
 expect(screen.queryByLabelText('Borrower QR or School ID')).toBeNull()
 expect(screen.getByRole('link',{name:'Open full counter'}).getAttribute('href')).toBe('/librarian/circulation')
 expect(screen.queryByText(/More library information/)).toBeNull()
 expect(screen.queryByRole('heading',{name:'Occupied library seats'})).toBeNull()
 expect(screen.getByRole('heading',{name:'Popular categories'})).toBeTruthy()
 const cards=screen.getByRole('region',{name:'Daily action cards'})
 expect(within(cards).getAllByRole('button')).toHaveLength(4)
 expect(within(cards).getByRole('link',{name:/Books in repair/}).getAttribute('href')).toContain('condition=For%20Repair')
 expect(screen.getByText('Grade 11 — STEM')).toBeTruthy();expect(screen.getByText('2nd Year — BSIT')).toBeTruthy()
 fireEvent.change(screen.getByRole('combobox',{name:'Department'}),{target:{value:'College'}})
 fireEvent.change(screen.getByRole('combobox',{name:'Strand or program'}),{target:{value:'BSHM'}})
 await waitFor(()=>expect(deskDashboardApi.tasks).toHaveBeenLastCalledWith(expect.objectContaining({department:'College',program:'BSHM'}),expect.any(AbortSignal)))
 fireEvent.click(screen.getByRole('button',{name:'Export filtered list'}))
 await waitFor(()=>expect(deskDashboardApi.export).toHaveBeenCalledWith(expect.objectContaining({department:'College',program:'BSHM'})))
})
it('one click queues school emails and refreshes status without clearing task filters',async()=>{
 open();await screen.findByText('Ana Flores');fireEvent.change(screen.getByLabelText('Search dashboard tasks'),{target:{value:'Ana'}})
 await waitFor(()=>expect(deskDashboardApi.tasks).toHaveBeenLastCalledWith(expect.objectContaining({q:'Ana'}),expect.any(AbortSignal)))
 const beforeReminder=vi.mocked(deskDashboardApi.tasks).mock.calls.length
 fireEvent.click(screen.getByRole('button',{name:'Send email reminders'}))
 await screen.findByText(/8 email reminders queued/)
 expect(screen.queryByRole('dialog',{name:'Review overdue reminders'})).toBeNull()
 expect(deskDashboardApi.queue).toHaveBeenCalledTimes(1)
 expect((screen.getByLabelText('Search dashboard tasks') as HTMLInputElement).value).toBe('Ana')
 await waitFor(()=>expect(deskDashboardApi.tasks).toHaveBeenCalledTimes(beforeReminder+1))
})
it('prevents repeat clicks while sending and replaces the action with the latest email status',async()=>{
 open();await screen.findByText('Ana Flores')
 let complete!:(value:{queued:number;skipped:number;channel:string})=>void
 vi.mocked(deskDashboardApi.queue).mockImplementationOnce(()=>new Promise(resolve=>{complete=resolve}))
 const button=screen.getByRole('button',{name:'Send email reminders'})
 fireEvent.click(button)
 await waitFor(()=>expect(deskDashboardApi.queue).toHaveBeenCalledTimes(1))
 expect((button as HTMLButtonElement).disabled).toBe(true)
 fireEvent.click(button)
 expect(deskDashboardApi.queue).toHaveBeenCalledTimes(1)
 vi.mocked(deskDashboardApi.tasks).mockResolvedValue({...dashboardPreviewTasks,items:dashboardPreviewTasks.items.map(row=>({...row,reminderStatus:'Queued'}))})
 complete({queued:8,skipped:0,channel:'School email'})
 await screen.findAllByText('Email: Queued')
 expect(screen.queryByRole('button',{name:'Send email reminder'})).toBeNull()
 vi.mocked(deskDashboardApi.tasks).mockResolvedValue({...dashboardPreviewTasks,items:dashboardPreviewTasks.items.map(row=>({...row,reminderStatus:'Sent'}))})
 fireEvent.click(screen.getByRole('button',{name:'Refresh dashboard'}))
 await screen.findAllByText('Email: Sent')
})
