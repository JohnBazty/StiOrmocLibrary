import { cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react'
import { afterEach, beforeEach, expect, it, vi } from 'vitest'
import { ClearanceScheduleEditor } from './ClearanceScheduleEditor'
const api = vi.hoisted(() => ({ terms: vi.fn(), schedule: vi.fn(), saveSchedule: vi.fn(), cancelSchedule: vi.fn() }))
vi.mock('./clearance-api', () => ({ clearanceApi: api }))
it('waits for the semester read before claiming no semester exists', () => {
  api.terms.mockReturnValueOnce(new Promise(() => {}))
  render(<ClearanceScheduleEditor />)
  expect(screen.getByRole('status').textContent).toContain('Loading semesters')
  expect(screen.queryByText(/No semester is available/)).toBeNull()
})
const empty = { termId: 1, deadlineAt: null, version: 0, windows: [] }
const row = { id: 7, group: 'BSIT', startsAt: '2026-12-01T00:00:00.000Z', endsAt: '2026-12-03T09:00:00.000Z', version: 1, status: 'Upcoming' }
beforeEach(() => {
  api.terms.mockResolvedValue([{ id: 1, academic_year: '2026–2027', term_name: 'First semester', is_active: 1 }])
  api.schedule.mockResolvedValue(empty)
})
afterEach(() => { cleanup(); vi.resetAllMocks() })
async function open() { render(<ClearanceScheduleEditor />); await waitFor(() => expect(screen.getByRole('button', { name: 'Add schedule' }).hasAttribute('disabled')).toBe(false)); fireEvent.click(screen.getByRole('button', { name: 'Add schedule' })) }
function fill() {
  fireEvent.click(screen.getByLabelText('Continuous period'))
  fireEvent.change(screen.getByLabelText('Group'), { target: { value: 'BSIT' } })
  fireEvent.change(screen.getByLabelText('Opens (Manila time)'), { target: { value: '2026-12-01T08:00' } })
  fireEvent.change(screen.getByLabelText('Closes (Manila time)'), { target: { value: '2026-12-03T17:00' } })
}
it('reviews group dates before saving exact Manila instants and immediately updates the list', async () => {
  api.saveSchedule.mockResolvedValue({ ...empty, windows: [row] })
  await open(); fill(); fireEvent.click(screen.getByRole('button', { name: 'Review schedule' }))
  expect(api.saveSchedule).not.toHaveBeenCalled()
  fireEvent.click(screen.getByRole('button', { name: 'Confirm schedule' }))
  expect(await screen.findByText('Clearance schedule saved. Students will see their applicable dates.')).toBeTruthy()
  expect(api.saveSchedule).toHaveBeenCalledWith(expect.objectContaining({ termId: 1, id: null, version: 0, group: 'BSIT', startsAt: row.startsAt, endsAt: row.endsAt, requestKey: expect.any(String) }))
  expect(screen.getByRole('button', { name: 'Cancel schedule' })).toBeTruthy()
})
it('selects separate days, reviews them, and saves only those days in Manila time', async () => {
  api.saveSchedule.mockResolvedValue(empty)
  await open()
  fireEvent.change(screen.getByLabelText('Calendar month'), { target: { value: '2026-12' } })
  fireEvent.click(screen.getByRole('button', { name: 'December 1, 2026' }))
  fireEvent.click(screen.getByRole('button', { name: 'December 3, 2026' }))
  fireEvent.click(screen.getByRole('button', { name: 'Review schedule' }))
  expect(api.saveSchedule).not.toHaveBeenCalled()
  expect(screen.getByText('2 days · All groups')).toBeTruthy()
  fireEvent.click(screen.getByRole('button', { name: 'Confirm schedule' }))
  await screen.findByText('2 clearance days saved. Students will see their applicable dates.')
  expect(api.saveSchedule).toHaveBeenCalledTimes(2)
  expect(api.saveSchedule.mock.calls.map(([input]) => [input.startsAt, input.endsAt])).toEqual([
    ['2026-12-01T00:00:00.000Z', '2026-12-01T09:00:00.000Z'],
    ['2026-12-03T00:00:00.000Z', '2026-12-03T09:00:00.000Z'],
  ])
  expect(api.saveSchedule.mock.calls[0][0].requestKey).not.toBe(api.saveSchedule.mock.calls[1][0].requestKey)
})
it('keeps unsaved days after a partial failure and retries with the same submission key', async () => {
  api.saveSchedule.mockResolvedValueOnce(empty).mockRejectedValueOnce(new Error('Connection interrupted.')).mockResolvedValue(empty)
  await open()
  fireEvent.change(screen.getByLabelText('Calendar month'), { target: { value: '2026-12' } })
  fireEvent.click(screen.getByRole('button', { name: 'December 1, 2026' }))
  fireEvent.click(screen.getByRole('button', { name: 'December 3, 2026' }))
  fireEvent.click(screen.getByRole('button', { name: 'Review schedule' }))
  fireEvent.click(screen.getByRole('button', { name: 'Confirm schedule' }))
  expect((await screen.findByRole('alert')).textContent).toContain('1 day saved. Remaining days are still selected.')
  expect(screen.getByRole('button', { name: 'December 1, 2026' }).getAttribute('aria-pressed')).toBe('false')
  expect(screen.getByRole('button', { name: 'December 3, 2026' }).getAttribute('aria-pressed')).toBe('true')
  fireEvent.click(screen.getByRole('button', { name: 'Review schedule' }))
  fireEvent.click(screen.getByRole('button', { name: 'Confirm schedule' }))
  await screen.findByText('1 clearance day saved. Students will see their applicable dates.')
  expect(api.saveSchedule.mock.calls[2][0]).toEqual(api.saveSchedule.mock.calls[1][0])
})
it('requires a day and allows deselecting a day before review', async () => {
  await open()
  fireEvent.change(screen.getByLabelText('Calendar month'), { target: { value: '2026-12' } })
  const day = screen.getByRole('button', { name: 'December 1, 2026' })
  fireEvent.click(day); fireEvent.click(day)
  fireEvent.click(screen.getByRole('button', { name: 'Review schedule' }))
  expect(await screen.findByText('Choose at least one day.')).toBeTruthy()
  expect(api.saveSchedule).not.toHaveBeenCalled()
})
it('retains selected days across months and applies the chosen daily hours', async () => {
  api.saveSchedule.mockResolvedValue(empty)
  await open()
  fireEvent.change(screen.getByLabelText('Calendar month'), { target: { value: '2026-12' } })
  fireEvent.click(screen.getByRole('button', { name: 'December 31, 2026' }))
  fireEvent.change(screen.getByLabelText('Calendar month'), { target: { value: '2027-01' } })
  fireEvent.click(screen.getByRole('button', { name: 'January 2, 2027' }))
  expect(screen.getByRole('button', { name: 'Remove December 31, 2026' })).toBeTruthy()
  fireEvent.change(screen.getByLabelText('Opening time (Manila time)'), { target: { value: '09:30' } })
  fireEvent.change(screen.getByLabelText('Closing time (Manila time)'), { target: { value: '12:00' } })
  fireEvent.click(screen.getByRole('button', { name: 'Review schedule' }))
  fireEvent.click(screen.getByRole('button', { name: 'Confirm schedule' }))
  await screen.findByText('2 clearance days saved. Students will see their applicable dates.')
  expect(api.saveSchedule.mock.calls.map(([input]) => [input.startsAt, input.endsAt])).toEqual([
    ['2026-12-31T01:30:00.000Z', '2026-12-31T04:00:00.000Z'],
    ['2027-01-02T01:30:00.000Z', '2027-01-02T04:00:00.000Z'],
  ])
})
it('rejects daily closing hours before opening hours', async () => {
  await open()
  fireEvent.change(screen.getByLabelText('Calendar month'), { target: { value: '2026-12' } })
  fireEvent.click(screen.getByRole('button', { name: 'December 1, 2026' }))
  fireEvent.change(screen.getByLabelText('Closing time (Manila time)'), { target: { value: '07:00' } })
  fireEvent.click(screen.getByRole('button', { name: 'Review schedule' }))
  expect(await screen.findByText('Closing time must be after opening time.')).toBeTruthy()
  expect(api.saveSchedule).not.toHaveBeenCalled()
})
it('edits an existing period with its original version without creating daily schedules', async () => {
  api.schedule.mockResolvedValue({ ...empty, windows: [row] })
  api.saveSchedule.mockResolvedValue({ ...empty, windows: [{ ...row, version: 2 }] })
  render(<ClearanceScheduleEditor />)
  fireEvent.click(await screen.findByRole('button', { name: 'Edit' }))
  expect((screen.getByLabelText('Opens (Manila time)') as HTMLInputElement).value).toBe('2026-12-01T08:00')
  fireEvent.click(screen.getByRole('button', { name: 'Review schedule' }))
  fireEvent.click(screen.getByRole('button', { name: 'Confirm schedule' }))
  await screen.findByText('Clearance schedule saved. Students will see their applicable dates.')
  expect(api.saveSchedule).toHaveBeenCalledWith(expect.objectContaining({ id: row.id, version: row.version, startsAt: row.startsAt, endsAt: row.endsAt }))
  expect(api.saveSchedule).toHaveBeenCalledTimes(1)
})
it('retains entered dates after overlap failures and tab changes', async () => {
  api.saveSchedule.mockRejectedValue(new Error('This group already has a schedule during that period.'))
  await open(); fill(); fireEvent.click(screen.getByRole('button', { name: 'Review schedule' })); fireEvent.click(screen.getByRole('button', { name: 'Confirm schedule' }))
  expect(await screen.findByRole('alert')).toBeTruthy()
  fireEvent(window, new Event('focus'))
  await waitFor(() => expect(api.schedule.mock.calls.length).toBeGreaterThan(1))
  expect((screen.getByLabelText('Opens (Manila time)') as HTMLInputElement).value).toBe('2026-12-01T08:00')
  expect((screen.getByLabelText('Group') as HTMLSelectElement).value).toBe('BSIT')
})
it('requires a cancellation review and removes the cancelled period after confirmation', async () => {
  api.schedule.mockResolvedValue({ ...empty, windows: [row] }); api.cancelSchedule.mockResolvedValue(empty)
  render(<ClearanceScheduleEditor />); fireEvent.click(await screen.findByRole('button', { name: 'Cancel schedule' }))
  expect(api.cancelSchedule).not.toHaveBeenCalled()
  fireEvent.click(screen.getByRole('button', { name: 'Confirm cancellation' }))
  expect(await screen.findByText('Schedule cancelled. Its change history is retained.')).toBeTruthy()
  expect(api.cancelSchedule).toHaveBeenCalledWith(7, 1, 1)
  expect(screen.queryByRole('button', { name: 'Cancel schedule' })).toBeNull()
})
it('rejects a closing time before the opening time without calling the API', async () => {
  await open(); fill(); fireEvent.change(screen.getByLabelText('Closes (Manila time)'), { target: { value: '2026-11-30T17:00' } })
  fireEvent.click(screen.getByRole('button', { name: 'Review schedule' }))
  expect(await screen.findByText('Closing time must be after opening time.')).toBeTruthy()
  expect(api.saveSchedule).not.toHaveBeenCalled()
})
