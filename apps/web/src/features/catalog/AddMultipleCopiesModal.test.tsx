import { cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react'
import { MemoryRouter } from 'react-router-dom'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { AddMultipleCopiesModal } from './AddMultipleCopiesModal'

const api = vi.hoisted(() => ({ createBulkBook: vi.fn(), lookupIsbn: vi.fn() }))
const classification = vi.hoisted(() => ({ lookup: vi.fn() }))
vi.mock('./dewey-api', () => ({ deweyApi: classification }))
vi.mock('./catalog-api', () => ({ catalogApi: api, ApiError: class extends Error {} }))
vi.mock('./BookLabelSheet', () => ({ BookLabelSheet: () => <div data-testid="inline-label-preview">Generated labels</div> }))

const shelfApi = vi.hoisted(() => ({ listShelves: vi.fn() }))
vi.mock('../categories/category-api', () => ({ categoryApi: shelfApi, CategoryApiError: class extends Error {} }))
beforeEach(() => { shelfApi.listShelves.mockResolvedValue(['Cabinet 4-B', 'Aisle 3'].map((label,index) => ({id:index+1,label,columnCount:1,rowCount:1,defaultCapacity:50,capacityConfigured:true,status:'Active',version:1,used:0,capacity:50,remaining:50,compartments:[{column:1,row:1,capacity:50,used:0,remaining:50,status:'Available'}]}))); })
beforeEach(() => { classification.lookup.mockReset(); classification.lookup.mockResolvedValue({isbn:'9780132350884',status:'not_found',candidates:[]}) })

const categories = [
  { categoryId: 1, categoryName: 'Programming', shelfLocation: 'Cabinet 4-B' },
  { categoryId: 2, categoryName: 'Database', shelfLocation: 'Aisle 3' },
]

describe('AddMultipleCopiesModal', () => {
  it('requires review before saving and invalidates it when the draft changes', async () => {
    api.lookupIsbn.mockResolvedValue({isbn:'9780132350884',title:'Clean Code',author:'Sample author',source:'local_catalog'})
    api.createBulkBook.mockResolvedValue({titleId:8,createdTitle:true,numberOfCopies:3,copies:[]})
    render(<MemoryRouter><AddMultipleCopiesModal categories={categories} onCreated={vi.fn()} onClose={vi.fn()} /></MemoryRouter>)
    expect(screen.getByText('More book details').closest('details')?.open).toBe(false)
    fireEvent.change(screen.getByLabelText(/Title \*/i),{target:{value:'Reviewed title'}})
    fireEvent.change(screen.getByLabelText(/Author \*/i),{target:{value:'Sample author'}})
    fireEvent.change(screen.getByLabelText(/ISBN \*/i),{target:{value:'9780132350884'}})
    fireEvent.change(screen.getByLabelText(/Category \*/i),{target:{value:'1'}})
    fireEvent.blur(screen.getByLabelText(/ISBN \*/i))
    await waitFor(()=>expect(classification.lookup).toHaveBeenCalled())
    await waitFor(()=>expect((screen.getByRole('button',{name:'Review book and copies'}) as HTMLButtonElement).disabled).toBe(false))
    fireEvent.click(screen.getByRole('button',{name:'Review book and copies'}))
    expect(api.createBulkBook).not.toHaveBeenCalled()
    expect(await screen.findByRole('button',{name:'Add book and 2 copies'})).toBeTruthy()
    fireEvent.change(screen.getByLabelText(/Number of copies/i),{target:{value:'3'}})
    expect(screen.queryByRole('button',{name:'Add book and 2 copies'})).toBeNull()
    fireEvent.click(screen.getByRole('button',{name:'Review book and copies'}))
    fireEvent.click(await screen.findByRole('button',{name:'Add book and 3 copies'}))
    await waitFor(()=>expect(api.createBulkBook).toHaveBeenCalledWith(expect.objectContaining({title:'Reviewed title',number_of_copies:'3'})))
  })

  it('requires a fresh review when a pending Dewey lookup changes the entry', async () => {
    let resolveLookup!: (result: unknown) => void
    classification.lookup.mockImplementation(() => new Promise(resolve => { resolveLookup = resolve }))
    api.lookupIsbn.mockResolvedValue({isbn:'9780132350884',title:'Fixture title',author:'Fixture author',source:'local_catalog'})
    render(<MemoryRouter><AddMultipleCopiesModal categories={categories} onCreated={vi.fn()} onClose={vi.fn()} /></MemoryRouter>)
    fireEvent.change(screen.getByLabelText(/Title \*/i),{target:{value:'Fixture title'}})
    fireEvent.change(screen.getByLabelText(/Author \*/i),{target:{value:'Fixture author'}})
    fireEvent.change(screen.getByLabelText(/ISBN \*/i),{target:{value:'9780132350884'}})
    fireEvent.blur(screen.getByLabelText(/ISBN \*/i))
    fireEvent.change(screen.getByLabelText(/Category \*/i),{target:{value:'1'}})
    await waitFor(()=>expect(classification.lookup).toHaveBeenCalled())
    fireEvent.click(screen.getByRole('button',{name:'Review book and copies'}))
    expect(await screen.findByRole('button',{name:'Add book and 2 copies'})).toBeTruthy()
    resolveLookup({isbn:'9780132350884',status:'matched',candidates:[{code:'005.1'}]})
    await waitFor(()=>expect(screen.queryByRole('button',{name:'Add book and 2 copies'})).toBeNull())
    expect(api.createBulkBook).not.toHaveBeenCalled()
    expect((screen.getByRole('button',{name:'Review book and copies'}) as HTMLButtonElement).disabled).toBe(true)
    fireEvent.click(screen.getByRole('checkbox',{name:'I reviewed this Dewey number'}))
    fireEvent.click(screen.getByRole('button',{name:'Review book and copies'}))
    expect(await screen.findByRole('button',{name:'Add book and 2 copies'})).toBeTruthy()
  })

  it('opens optional details when a hidden optional field fails validation', async () => {
    api.lookupIsbn.mockResolvedValue({isbn:'9780132350884',title:'Fixture title',author:'Fixture author',source:'local_catalog'})
    render(<MemoryRouter><AddMultipleCopiesModal categories={categories} onCreated={vi.fn()} onClose={vi.fn()} /></MemoryRouter>)
    fireEvent.change(screen.getByLabelText(/Title \*/i),{target:{value:'Fixture title'}})
    fireEvent.change(screen.getByLabelText(/Author \*/i),{target:{value:'Fixture author'}})
    fireEvent.change(screen.getByLabelText(/ISBN \*/i),{target:{value:'9780132350884'}})
    fireEvent.change(screen.getByLabelText(/Category \*/i),{target:{value:'1'}})
    fireEvent.change(screen.getByLabelText(/^Cost price/i),{target:{value:'-1'}})
    await waitFor(()=>expect((screen.getByRole('button',{name:'Review book and copies'}) as HTMLButtonElement).disabled).toBe(false))
    fireEvent.click(screen.getByRole('button',{name:'Review book and copies'}))
    expect(screen.getByText('More book details').closest('details')?.open).toBe(true)
    expect(screen.queryByRole('button',{name:'Add book and 2 copies'})).toBeNull()
    expect(api.createBulkBook).not.toHaveBeenCalled()
  })
  it('blocks a full default compartment and sends a manually chosen compartment', async () => {
    shelfApi.listShelves.mockResolvedValueOnce([{id:1,label:'Cabinet 4-B',columnCount:2,rowCount:1,defaultCapacity:5,capacityConfigured:true,status:'Active',version:1,used:6,capacity:10,remaining:4,compartments:[{column:1,row:1,capacity:5,used:5,remaining:0,status:'Full'},{column:2,row:1,capacity:5,used:1,remaining:4,status:'Available'}]}])
    api.lookupIsbn.mockResolvedValue({isbn:'9780132350884',title:'Clean Code',author:'Robert C. Martin',publisher:'',publicationYear:2008,source:'local_catalog'})
    api.createBulkBook.mockResolvedValue({ titleId: 8, createdTitle: false, numberOfCopies: 2, copies: [] })
    render(<MemoryRouter><AddMultipleCopiesModal categories={categories} onCreated={vi.fn()} onClose={vi.fn()} /></MemoryRouter>)
    fireEvent.change(screen.getByLabelText(/Category \*/i),{target:{value:'1'}})
    fireEvent.change(screen.getByLabelText(/Title \*/i),{target:{value:'Clean Code'}})
    fireEvent.change(screen.getByLabelText(/Author \*/i),{target:{value:'Robert C. Martin'}})
    fireEvent.change(screen.getByLabelText(/ISBN \*/i),{target:{value:'9780132350884'}})
    await screen.findByRole('option',{name:'Column 2'})
    expect(screen.getByText(/Only 0 spaces remain/)).toBeTruthy()
    expect((screen.getByRole('button',{name:/Review book and copies/i}) as HTMLButtonElement).disabled).toBe(true)
    fireEvent.change(screen.getByLabelText('Column'),{target:{value:'2'}})
    fireEvent.click(screen.getByRole('button',{name:/Review book and copies/i}))
    fireEvent.click(await screen.findByRole('button', { name: /^Add book and \d+ cop/ }))
    await waitFor(()=>expect(api.createBulkBook).toHaveBeenCalledWith(expect.objectContaining({locationId:'1',shelfColumn:2,shelfRow:1,shelf_location:'Cabinet 4-B'})))
  })

  it('reviews required metadata while preserving optional blanks and librarian-managed fields', async () => {
    api.lookupIsbn.mockResolvedValue({ isbn: '9780132350884', title: 'Clean Code', author: 'Robert C. Martin', publisher: 'Prentice Hall', publicationYear: 2008, source: 'google_books' })
    render(<MemoryRouter><AddMultipleCopiesModal categories={categories} onCreated={() => undefined} onClose={() => undefined} /></MemoryRouter>)
    fireEvent.change(screen.getByLabelText(/Number of copies/i), { target: { value: '4' } })
    fireEvent.change(screen.getByLabelText(/Call number/i), { target: { value: '005.1 MAR' } })
    fireEvent.change(screen.getByLabelText(/Category \*/i), { target: { value: '2' } })
    const isbn = screen.getByLabelText(/ISBN \*/i)
    fireEvent.change(isbn, { target: { value: '9780132350884' } })
    fireEvent.blur(isbn)
    await waitFor(() => expect(api.lookupIsbn).toHaveBeenCalledWith('9780132350884', expect.any(AbortSignal)))
    fireEvent.click(screen.getByRole('button',{name:'Auto-fill missing required information'}))
    fireEvent.click(await screen.findByRole('button',{name:'Apply required details to draft'}))
    await screen.findByDisplayValue('Clean Code')
    expect((screen.getByLabelText(/Title \*/i) as HTMLInputElement).value).toBe('Clean Code')
    expect((screen.getByLabelText(/Author \*/i) as HTMLInputElement).value).toBe('Robert C. Martin')
    expect((screen.getByLabelText(/Publisher/i) as HTMLInputElement).value).toBe('')
    expect((screen.getByLabelText(/Publication year/i) as HTMLInputElement).value).toBe('')
    expect((screen.getByLabelText(/Number of copies/i) as HTMLInputElement).value).toBe('4')
    expect((screen.getByLabelText(/Call number/i) as HTMLInputElement).value).toBe('005.1 MAR')
    expect((screen.getByLabelText(/Category \*/i) as HTMLSelectElement).value).toBe('2')
    expect((screen.getByLabelText(/Book location \*/i) as HTMLInputElement).value).toBe('Aisle 3')
    expect(screen.getByLabelText(/Book location \*/i).tagName).toBe('SELECT')
    expect(screen.getByText(/Book match found from Google Books/i)).toBeTruthy()
  })

  it('defaults to the category shelf and renders the inline preview', async () => {
    api.createBulkBook.mockResolvedValue({ titleId: 8, createdTitle: true, numberOfCopies: 2, copies: [] })
    const created = vi.fn()
    render(<MemoryRouter><AddMultipleCopiesModal categories={categories} onCreated={created} onClose={() => undefined} /></MemoryRouter>)
    expect(screen.getByRole('option', { name: 'Programming' })).toBeTruthy()
    fireEvent.change(screen.getByLabelText(/Category \*/i), { target: { value: '1' } })
    expect((screen.getByLabelText(/Book location \*/i) as HTMLInputElement).value).toBe('Cabinet 4-B')
    fireEvent.change(screen.getByLabelText(/Title \*/i), { target: { value: 'Clean Code' } })
    fireEvent.change(screen.getByLabelText(/Author \*/i), { target: { value: 'Robert C. Martin' } })
    fireEvent.change(screen.getByLabelText(/ISBN \*/i), { target: { value: '9780132350884' } })
    await waitFor(() => expect((screen.getByRole('button', { name: /Review book and copies/i }) as HTMLButtonElement).disabled).toBe(false))
    fireEvent.click(screen.getByRole('button', { name: /Review book and copies/i }))
    fireEvent.click(await screen.findByRole('button', { name: /^Add book and \d+ cop/ }))
    await waitFor(() => expect(api.createBulkBook).toHaveBeenCalledWith(expect.objectContaining({ category_id: '1', shelf_location: 'Cabinet 4-B', number_of_copies: '2' })))
    expect(api.createBulkBook.mock.calls[0][0]).not.toHaveProperty('purchase_price')
    expect(await screen.findByTestId('inline-label-preview')).toBeTruthy()
    expect(screen.getByText(/Saved to inventory: 2 physical copies/i)).toBeTruthy()
    expect(screen.getByRole('button', { name: /Close and view inventory/i })).toBeTruthy()
    expect(created).toHaveBeenCalled()
  })

  it('explains an invalid check digit and accepts a formatted ISBN-10', async () => {
    api.createBulkBook.mockResolvedValue({ titleId: 9, createdTitle: true, numberOfCopies: 1, copies: [] })
    render(<MemoryRouter><AddMultipleCopiesModal categories={categories} onCreated={() => undefined} onClose={() => undefined} /></MemoryRouter>)
    fireEvent.change(screen.getByLabelText(/Title \*/i), { target: { value: "Charlotte's Web" } })
    fireEvent.change(screen.getByLabelText(/Author \*/i), { target: { value: 'E. B. White' } })
    fireEvent.change(screen.getByLabelText(/Category \*/i), { target: { value: '1' } })
    fireEvent.change(screen.getByLabelText(/ISBN \*/i), { target: { value: '9780062638500' } })
    expect(screen.getByText('Incorrect check digit. The final digit must be 2.')).toBeTruthy()
    expect((screen.getByRole('button', { name: /Review book and copies/i }) as HTMLButtonElement).disabled).toBe(true)

    fireEvent.change(screen.getByLabelText(/ISBN \*/i), { target: { value: 'ISBN-10: 0-13-235088-2' } })
    expect(screen.getByText('Valid ISBN-10 checksum')).toBeTruthy()
    await waitFor(() => expect((screen.getByRole('button', { name: /Review book and copies/i }) as HTMLButtonElement).disabled).toBe(false))
    fireEvent.click(screen.getByRole('button', { name: /Review book and copies/i }))
    fireEvent.click(await screen.findByRole('button', { name: /^Add book and \d+ cop/ }))
    await waitFor(() => expect(api.createBulkBook).toHaveBeenCalledWith(expect.objectContaining({ isbn: '0132350882' })))
  })

  it('sends the book register fields with the entry', async () => {
    api.createBulkBook.mockResolvedValue({ titleId: 10, createdTitle: true, numberOfCopies: 1, copies: [] })
    render(<MemoryRouter><AddMultipleCopiesModal categories={categories} onCreated={() => undefined} onClose={() => undefined} /></MemoryRouter>)
    fireEvent.change(screen.getByLabelText(/Title \*/i), { target: { value: 'Clean Code' } })
    fireEvent.change(screen.getByLabelText(/Author \*/i), { target: { value: 'Robert C. Martin' } })
    fireEvent.change(screen.getByLabelText(/ISBN \*/i), { target: { value: '9780132350884' } })
    fireEvent.change(screen.getByLabelText(/Category \*/i), { target: { value: '1' } })
    fireEvent.change(screen.getByLabelText(/^Class/i), { target: { value: '005.1' } })
    fireEvent.change(screen.getByLabelText(/^Edition/i), { target: { value: '1st ed.' } })
    fireEvent.change(screen.getByLabelText(/^Volumes/i), { target: { value: '1 vol.' } })
    fireEvent.change(screen.getByLabelText(/^Pages/i), { target: { value: '464' } })
    fireEvent.change(screen.getByLabelText(/^Source of fund/i), { target: { value: 'Donation' } })
    fireEvent.change(screen.getByLabelText(/^Fund details/i), { target: { value: 'Alumni' } })
    fireEvent.change(screen.getByLabelText(/^Cost price/i), { target: { value: '450' } })
    fireEvent.change(screen.getByLabelText(/^Date received/i), { target: { value: '2026-11-02' } })
    fireEvent.change(screen.getByLabelText(/^Remarks/i), { target: { value: 'Donated set' } })
    await waitFor(() => expect((screen.getByRole('button', { name: /Review book and copies/i }) as HTMLButtonElement).disabled).toBe(false))
    fireEvent.click(screen.getByRole('button', { name: /Review book and copies/i }))
    fireEvent.click(await screen.findByRole('button', { name: /^Add book and \d+ cop/ }))
    await waitFor(() => expect(api.createBulkBook).toHaveBeenLastCalledWith(expect.objectContaining({
      classification: '005.1', edition: '1st ed.', volumes: '1 vol.', pages: '464', remarks: 'Donated set',
      fund_source: 'Donation', fund_detail: 'Alumni', cost_php: '450', received_on: '2026-11-02',
    })))
  })

  it('asks before closing once details were typed, and closes at once when empty', () => {
    const closed = vi.fn()
    const { unmount } = render(<MemoryRouter><AddMultipleCopiesModal categories={categories} onCreated={() => undefined} onClose={closed} /></MemoryRouter>)
    fireEvent.click(screen.getByRole('button', { name: 'Cancel' }))
    expect(closed).toHaveBeenCalledTimes(1)
    fireEvent.change(screen.getByLabelText(/Title \*/i), { target: { value: 'Clean Code' } })
    fireEvent.click(screen.getByRole('button', { name: 'Close' }))
    expect(screen.getByRole('alertdialog', { name: 'You have unsaved changes' })).toBeTruthy()
    fireEvent.click(screen.getByRole('button', { name: 'Keep editing' }))
    expect(closed).toHaveBeenCalledTimes(1)
    fireEvent.click(screen.getByRole('button', { name: 'Cancel' }))
    fireEvent.click(screen.getByRole('button', { name: 'Discard changes' }))
    expect(closed).toHaveBeenCalledTimes(2)
    unmount()
  })
})

afterEach(() => { cleanup(); vi.clearAllMocks() })
