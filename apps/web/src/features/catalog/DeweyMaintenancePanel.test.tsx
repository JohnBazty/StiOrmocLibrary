import { cleanup,fireEvent,render,screen,waitFor } from '@testing-library/react'
import { afterEach,expect,it,vi } from 'vitest'
import { DeweyMaintenancePanel } from './DeweyMaintenancePanel'
const api=vi.hoisted(()=>({copies:vi.fn(),classifications:vi.fn(),lookup:vi.fn(),assign:vi.fn(),saveClassification:vi.fn()}))
vi.mock('./AutomaticDeweyPanel',()=>({AutomaticDeweyPanel:()=>null}))
vi.mock('./dewey-api',()=>({deweyApi:api}))
afterEach(()=>{cleanup();vi.resetAllMocks()})
it('previews selected accessions and saves only reviewed copy versions',async()=>{
  api.copies.mockResolvedValue({total:2,items:[1,2].map(id=>({id,version:0,accession:`TEST-ACC-${id}`,title:'Test book',isbn:'9780132350884',code:null}))})
  api.classifications.mockResolvedValue([])
  api.lookup.mockResolvedValue({status:'matched',candidates:[{code:'005.100'}]})
  api.assign.mockResolvedValue({saved:true})
  render(<DeweyMaintenancePanel/> )
  fireEvent.click(await screen.findByLabelText('Select TEST-ACC-2'))
  fireEvent.click(screen.getByRole('button',{name:/Find missing Dewey numbers/}))
  expect(screen.getByText('TEST-ACC-2: Not assigned')).toBeTruthy()
  await screen.findByDisplayValue('005.100')
  expect((screen.getByRole('button',{name:'Save Dewey for 1 copy'}) as HTMLButtonElement).disabled).toBe(true)
  fireEvent.click(screen.getByLabelText(/I reviewed this Dewey number/))
  fireEvent.click(screen.getByRole('button',{name:'Save Dewey for 1 copy'}))
  await waitFor(()=>expect(api.assign).toHaveBeenCalledWith('9780132350884',{code:'005.100',source:'open_library',reviewed:true},[{id:2,version:0}]))
  await screen.findByText('Reviewed Dewey numbers saved for the selected copies.')
})
it('retains the review when a concurrent edit is rejected',async()=>{
  api.copies.mockResolvedValue({total:1,items:[{id:1,version:0,accession:'TEST-ACC-1',title:'Test',isbn:null,code:null}]})
  api.classifications.mockResolvedValue([])
  api.assign.mockRejectedValue(new Error('A selected copy changed. Reload and review it again.'))
  render(<DeweyMaintenancePanel/> )
  fireEvent.click(await screen.findByLabelText('Select TEST-ACC-1'))
  fireEvent.click(screen.getByRole('button',{name:/Find missing Dewey numbers/}))
  fireEvent.change(screen.getByLabelText('Dewey number'),{target:{value:'100'}})
  fireEvent.click(screen.getByLabelText(/I reviewed this Dewey number/))
  fireEvent.click(screen.getByRole('button',{name:'Save Dewey for 1 copy'}))
  await screen.findByRole('alert')
  expect((screen.getByLabelText('Dewey number') as HTMLInputElement).value).toBe('100')
})
it('saves a reusable classification and clears its completed draft',async()=>{
  api.copies.mockResolvedValue({items:[],total:0})
  api.classifications.mockResolvedValue([])
  api.saveClassification.mockResolvedValue({saved:true})
  render(<DeweyMaintenancePanel/> )
  fireEvent.click(screen.getByText('Maintain reusable Dewey classifications'))
  fireEvent.change(screen.getByLabelText('Classification number'),{target:{value:'005.100'}})
  fireEvent.change(screen.getByLabelText('Description (optional)'),{target:{value:'Programming'}})
  fireEvent.click(screen.getByRole('button',{name:'Add classification'}))
  await waitFor(()=>expect(api.saveClassification).toHaveBeenCalledWith({code:'005.100',description:'Programming',status:'Active'}))
  await screen.findByText('Dewey classification saved.')
  expect((screen.getByLabelText('Classification number') as HTMLInputElement).value).toBe('')
})
