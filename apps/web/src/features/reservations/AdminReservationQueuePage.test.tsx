import {cleanup,fireEvent,render,screen,waitFor} from '@testing-library/react'
import {MemoryRouter} from 'react-router-dom'
import {afterEach,beforeEach,expect,it,vi} from 'vitest'
import {AdminReservationQueuePage} from './AdminReservationQueuePage'
const api=vi.hoisted(()=>({queue:vi.fn(),adjustStatus:vi.fn(),swapCandidates:vi.fn(),swapCopy:vi.fn()}))
const schedules=vi.hoisted(()=>({queue:vi.fn()}))
vi.mock('./reservation-api',()=>({reservationApi:api}))
vi.mock('./borrowing-schedule-api',()=>({borrowingScheduleApi:schedules,pickupDateLabel:(date:string)=>date}))
vi.mock('../auth/auth-storage',()=>({getCurrentIdentity:()=>({role:'Staff'})}))
const row={reservationId:81,userId:7,userName:'Sample Student',institutionalId:'SAMPLE-7',userRole:'Student',materialTitle:'Waiting title',materialType:'Book',status:'pending',queuePosition:2,reservedAt:'2026-10-16T01:00:00Z',pickupDeadline:null,assignedCopyId:null,barcode:null,accessionNumber:null,shelfLocation:null}
const ready={...row,reservationId:82,materialTitle:'Ready title',status:'ready_for_pickup',queuePosition:1,barcode:'SAMPLE-COPY',assignedCopyId:4,pickupDeadline:'2026-10-17T01:00:00Z'}
beforeEach(()=>{api.queue.mockResolvedValue({items:[row,ready],pagination:{pages:1,total:2}});api.adjustStatus.mockResolvedValue({});schedules.queue.mockResolvedValue({available:true,items:[{scheduleId:1,title:'Future book',userName:'Sample Student',schoolId:'SAMPLE-7',userRole:'Student',pickupDate:'2026-11-21',requestedAt:'2026-11-19T02:00:00Z',preparationStartsAt:'2026-11-20T00:00:00+08:00',reason:null}],pagination:{pages:1,total:1}})})
afterEach(()=>{cleanup();vi.resetAllMocks()})
const open=()=>render(<MemoryRouter><AdminReservationQueuePage/></MemoryRouter>)
it('shows all active requests to Staff by default and exposes their queue position and pickup action',async()=>{
 open();await screen.findByText('Waiting title')
 expect(api.queue).toHaveBeenCalledWith(expect.objectContaining({status:'active'}),1)
 expect(screen.getByRole('heading',{name:'Book queue'})).toBeTruthy()
 expect(screen.getByText('Queue position #2')).toBeTruthy()
 expect(screen.getByRole('link',{name:'Start checkout'}).getAttribute('href')).toBe('/staff/circulation?requestId=82')
 expect(api.adjustStatus).not.toHaveBeenCalled()
})
it('keeps a direct counter handoff for staff without changing a request',async()=>{
 open();await screen.findByText('Waiting title')
 expect(screen.getByRole('link',{name:'Open counter'}).getAttribute('href')).toBe('/staff/circulation')
 expect(api.adjustStatus).not.toHaveBeenCalled()
})
it('marks the assigned copy ready only on staff action and keeps a route to checkout',async()=>{
 api.queue.mockResolvedValue({items:[{...row,status:'approved',assignedCopyId:4,barcode:'SAMPLE-COPY'}],pagination:{pages:1,total:1}})
 open();fireEvent.click(await screen.findByRole('button',{name:'Mark ready'}))
 await waitFor(()=>expect(api.adjustStatus).toHaveBeenCalledWith(81,'ready_for_pickup'))
 await screen.findByText('Waiting title is ready. Its pickup timer has started.')
 expect(document.body.textContent).not.toMatch(/\d+-hour|\d+ hours?/)
})
it('lets Staff change between waiting pickups and all history without creating a loan',async()=>{
 open();await screen.findByText('Waiting title')
 fireEvent.change(screen.getByLabelText('Request status'),{target:{value:'pending'}})
 await waitFor(()=>expect(api.queue).toHaveBeenLastCalledWith(expect.objectContaining({status:'pending'}),1))
 fireEvent.change(screen.getByLabelText('Request status'),{target:{value:''}})
 await waitFor(()=>expect(api.queue).toHaveBeenLastCalledWith(expect.objectContaining({status:''}),1))
 expect(api.adjustStatus).not.toHaveBeenCalled()
})
const cart={...row,reservationId:90,materialTitle:'Cart title',status:'approved',requestKind:'CartHandover',queuePosition:null,assignedCopyId:5,barcode:'CART-COPY',pickupDeadline:'2026-11-18T09:00:00Z'}
it('lists cart handovers under the kind filter with their auto-cancel time',async()=>{
 open();await screen.findByText('Waiting title')
 api.queue.mockResolvedValue({items:[cart],pagination:{pages:1,total:1}})
 fireEvent.change(screen.getByLabelText('Request kind'),{target:{value:'CartHandover'}})
 await waitFor(()=>expect(api.queue).toHaveBeenLastCalledWith(expect.objectContaining({kind:'CartHandover'}),1))
 await screen.findByText('Cart title')
 expect(screen.getByText(/Auto-cancels Nov 18, 2026, 5:00 PM/)).toBeTruthy()
 expect(screen.queryByRole('button',{name:'Mark ready'})).toBeNull()
 expect(screen.queryByText(/Queue position/)).toBeNull()
 expect(screen.queryByText(/Mark ready only after/)).toBeNull()
 expect(screen.getByRole('link',{name:'Start checkout'}).getAttribute('href')).toBe('/staff/circulation?requestId=90')
})
it('shows the empty state for an empty cart list',async()=>{
 open();await screen.findByText('Waiting title')
 api.queue.mockResolvedValue({items:[],pagination:{pages:1,total:0}})
 fireEvent.change(screen.getByLabelText('Request kind'),{target:{value:'CartHandover'}})
 await screen.findByText('No active cart handovers.')
})
it('shows why a waiting request was skipped',async()=>{
 api.queue.mockResolvedValue({items:[{...row,lastSkipReason:'Over borrowing limit',lastSkippedAt:'2026-11-18T02:00:00Z'}],pagination:{pages:1,total:1}})
 open();await screen.findByText(/Skipped: Over borrowing limit, Nov 18, 2026, 10:00 AM/)
})
it('keeps the queue first come, first served: a waiting request offers Cancel but no reordering',async()=>{
 open();await screen.findByText('Waiting title')
 expect(screen.getAllByRole('button',{name:'Cancel request'}).length).toBeGreaterThan(0)
 expect(screen.queryByRole('button',{name:'Move up'})).toBeNull()
 expect(screen.queryByRole('button',{name:'Move down'})).toBeNull()
})
it('swaps the copy from the list of eligible copies',async()=>{
 api.queue.mockResolvedValue({items:[{...row,status:'approved',assignedCopyId:4,barcode:'SAMPLE-COPY'}],pagination:{pages:1,total:1}})
 api.swapCandidates.mockResolvedValue([{physicalCopyId:4,barcode:'SAMPLE-COPY',accessionNumber:'A-1',shelfLocation:null},{physicalCopyId:6,barcode:'OTHER-COPY',accessionNumber:'A-2',shelfLocation:'Shelf 3'}])
 api.swapCopy.mockResolvedValue({})
 open();fireEvent.click(await screen.findByRole('button',{name:'Swap copy'}))
 await screen.findByText('OTHER-COPY')
 expect(screen.queryByText('A-1',{exact:false})).toBeNull()
 const dialog=screen.getByRole('dialog')
 fireEvent.click(screen.getByRole('radio'))
 fireEvent.click([...dialog.querySelectorAll('button')].find(b=>b.textContent==='Swap copy') as HTMLElement)
 await waitFor(()=>expect(api.swapCopy).toHaveBeenCalledWith(81,6))
})
it('closes the cancel dialog on Escape without cancelling',async()=>{
 open();await screen.findByText('Waiting title')
 fireEvent.click(screen.getAllByRole('button',{name:'Cancel request'})[0])
 expect(screen.getByRole('dialog',{name:'Cancel this book request?'})).toBeTruthy()
 fireEvent.keyDown(document,{key:'Escape'})
 expect(screen.queryByRole('dialog')).toBeNull()
 expect(api.adjustStatus).not.toHaveBeenCalled()
})
it('shows only the load error when swap candidates fail',async()=>{
 api.queue.mockResolvedValue({items:[{...row,status:'approved',assignedCopyId:4,barcode:'SAMPLE-COPY'}],pagination:{pages:1,total:1}})
 api.swapCandidates.mockRejectedValue(new Error('Could not load copies.'))
 open();fireEvent.click(await screen.findByRole('button',{name:'Swap copy'}))
 expect((await screen.findByRole('alert')).textContent).toBe('Could not load copies.')
 expect(screen.queryByText('No other copy is available to swap to.')).toBeNull()
})
